using EmailSslSender.Shared.Contracts.Audit;

namespace EmailSslSender.Modules.Settings.Contracts;

/// <summary>
/// События журнала, которые пишет модуль настроек.
/// </summary>
/// <remarks>
/// Публичный тип — на эти имена ссылаются тесты, а позже могут сослаться соседи. Имя события
/// не меняется никогда: оно лежит в строках журнала, а журнал append-only.
///
/// ⚠ <b>Событие ОДНО, и это осознанно.</b> Правка личного предпочтения в журнал не пишется:
/// «человек сменил себе тему» — это не действие с последствиями для других, а строк оно даёт
/// столько же, сколько все административные правки вместе. Тот же довод, по которому со стенда
/// убрали <c>permission_check</c>: журнал, состоящий из шума на три четверти, перестают читать.
///
/// ⚠ <b>Правка системной настройки пишется ВСЕГДА, и это половина смысла модуля.</b> Порог
/// блокировки, срок хранения журнала, признак «разрешённые проверки не пишутся» — правятся
/// обычной админкой, и вопрос «кто выключил запись» обязан иметь ответ. Значение при этом идёт
/// в <c>changes</c> открытым: настройка — не секрет, а знать «было 10, стало 1000» и есть
/// смысл записи.
/// </remarks>
public static class SettingsActions
{
    /// <summary>Изменена системная настройка.</summary>
    public static readonly AuditAction SystemUpdate = new("settings.system.update", "Изменена настройка");
}
