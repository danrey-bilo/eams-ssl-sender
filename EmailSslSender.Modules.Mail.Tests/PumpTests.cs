using EmailSslSender.Modules.Mail.Sending;

namespace EmailSslSender.Modules.Mail.Tests;

/// <summary>
/// Ход насоса: разрежение на пустой очереди и пробуждение письмом (этап 60.2).
/// </summary>
/// <remarks>
/// ⚠ ⚠ ⚠ <b>Насос ходил каждые пятнадцать секунд ВСЕГДА</b> — 11 520 холостых пар запросов в
/// сутки на установке, где почты нет вовсе. Разредить ход просто; цена простого решения — письмо
/// с кодом входа, которое ждут <b>прямо сейчас, у экрана</b>, уходит через минуту вместо
/// пятнадцати секунд. Это хуже, чем было.
///
/// ⚠ ⚠ <b>Поэтому разрежение и сигнал — одна работа, а не две.</b> Сигнал делает задержку
/// <b>меньше</b> прежней (ноль вместо пятнадцати секунд), и только при нём разрежение можно
/// вводить вообще. Проверяются оба, и в паре: зелёное разрежение при сломанном сигнале означало
/// бы ровно то ухудшение, ради недопущения которого сигнал и написан.
///
/// ⚠ <b>Арифметика вынесена в <c>Срок</c> и проверяется как чистая функция.</b> Прогон на
/// минуту реального времени — не проверка, а способ сделать сьют медленным и мигающим.
///
/// Мутация 2026-09-07: <c>Срок</c> перестал упираться в потолок → покраснел «срок не растёт выше
/// минуты». Вторая: сигнал не запоминается при незанятом ожидании → покраснел «взведённый сигнал
/// не теряется».
/// </remarks>
public sealed class PumpTests
{
    [Fact]
    public void Первые_пустые_проходы_ход_не_разрежают()
    {
        // ⚠ На установке с редкой, но живой почтой первый же пустой проход не должен удлинять
        // ожидание вдвое: письма приходят пачками, между пачками — тишина.
        foreach (var пустых in (int[])[0, 1, 2, 3])
        {
            MailDeliveryService.Срок(пустых).ShouldBe(TimeSpan.FromSeconds(15));
        }
    }

    [Fact]
    public void Дальше_срок_удваивается()
    {
        MailDeliveryService.Срок(4).ShouldBe(TimeSpan.FromSeconds(30));
        MailDeliveryService.Срок(5).ShouldBe(TimeSpan.FromSeconds(60));
    }

    [Fact]
    public void Срок_не_растёт_выше_минуты()
    {
        // ⚠ ⚠ Потолок несущий: сигнал внутрипроцессный, и письмо, положенное ДРУГИМ процессом,
        // дождётся только срока. Минута — предел, за которым это перестаёт быть незаметным;
        // без потолка после часа простоя первое письмо ждало бы сутки.
        foreach (var пустых in (int[])[6, 10, 100, 10_000])
        {
            MailDeliveryService.Срок(пустых).ShouldBe(TimeSpan.FromMinutes(1));
        }
    }

    /// <summary>
    /// Пустой проход, разбуженный сигналом, ход не разрежает и повторяется скоро.
    /// </summary>
    /// <remarks>
    /// ⚠ ⚠ Ревью 2026-09-15 (mail-1). Сигнал даётся до фиксации строки, и насос приходит раньше
    /// неё: захват пуст. Прежде такой проход считался обычным — сигнал израсходован, счётчик
    /// растёт, и на простаивающей установке код входа ждал минуту.
    /// </remarks>
    [Fact]
    public void Пустой_проход_по_сигналу_не_разрежает_ход_и_приходит_снова_скоро()
    {
        // Установка простаивала: пять пустых подряд, срок уже минута.
        var (пустых, срок) = MailDeliveryService.Следующий(было: 5, после: 6, поСигналу: true);

        пустых.ShouldBe(5, "письмо легло в очередь, а насос счёл его пустым проходом");
        срок.ShouldBe(MailDeliveryService.Догляд);
        срок.ShouldBeLessThan(TimeSpan.FromSeconds(15), "код входа ждал бы полный разрежённый срок");
    }

    [Fact]
    public void Пустой_догляд_без_сигнала_считается_обычным_пустым()
    {
        // Зеркало: без него «не разрежает» проходило бы и у насоса, который не разрежает никогда.
        var (пустых, срок) = MailDeliveryService.Следующий(было: 5, после: 6, поСигналу: false);

        пустых.ShouldBe(6);
        срок.ShouldBe(MailDeliveryService.Срок(6));
    }

    [Fact]
    public void Взятая_по_сигналу_порция_сбрасывает_счёт()
    {
        var (пустых, срок) = MailDeliveryService.Следующий(было: 5, после: 0, поСигналу: true);

        пустых.ShouldBe(0);
        срок.ShouldBe(TimeSpan.FromSeconds(15));
    }

    [Fact]
    public async Task Сигнал_будит_немедленно()
    {
        var сигнал = new MailWakeup();

        сигнал.Signal();

        // ⚠ Нулевое ожидание: если бы сигнал не был взведён, `WaitAsync(0)` вернул бы `false`
        // сразу. То есть проверка не зависит ни от какого таймера.
        (await сигнал.WaitAsync(TimeSpan.Zero, TestContext.Current.CancellationToken))
            .ShouldBeTrue("письмо легло в очередь, а насос его не заметил");
    }

    [Fact]
    public async Task Взведённый_сигнал_не_теряется()
    {
        var сигнал = new MailWakeup();

        // ⚠ ⚠ Письмо, положенное ровно во время прохода насоса, обязано разбудить СЛЕДУЮЩЕЕ
        // ожидание. Потеряйся сигнал — худший случай (полный разрежённый интервал) выпадал бы
        // ровно на самый занятый момент.
        сигнал.Signal();
        сигнал.Signal();

        var ct = TestContext.Current.CancellationToken;

        (await сигнал.WaitAsync(TimeSpan.Zero, ct)).ShouldBeTrue();

        // Второй сигнал не копится: насос забирает порцию целиком, а не по письму.
        (await сигнал.WaitAsync(TimeSpan.Zero, ct)).ShouldBeFalse();
    }

    [Fact]
    public async Task Без_сигнала_ожидание_кончается_сроком()
    {
        var сигнал = new MailWakeup();

        (await сигнал.WaitAsync(TimeSpan.FromMilliseconds(20), TestContext.Current.CancellationToken))
            .ShouldBeFalse("никто не будил — насос обязан проснуться сам, по сроку");
    }
}
