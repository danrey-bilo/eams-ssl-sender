namespace EmailSslSender.IntegrationTests;

/// <summary>
/// Обвязка настроек убирает за собой.
/// </summary>
/// <remarks>
/// ⚠ ⚠ <b>Проверяется ОБВЯЗКА, а не приложение, и это законный тест.</b> Обвязка, чинящая
/// заражение общей таблицы, сама может сломаться — и сломается тихо: следующий прогон
/// покраснеет в чужих модулях, которые про настройки ничего не знают. На Python-версии так и
/// было: пять оставленных строк уронили 151 тест, и причину нашли только полным прогоном.
///
/// ⚠ <b>Обратное направление проверено вручную 2026-08-29 и здесь быть не может:</b> зонд,
/// оставивший строку намеренно, роняет инвариант коллекции с текстом «осталось строк: 1» —
/// то есть роняет весь прогон. Постоянный тест, который обязан ронять прогон, — не тест.
/// Красно-зелёная проверка (правило 8) для этой обвязки выглядит так и только так.
/// </remarks>
[Collection(SenderHost.Collection)]
public sealed class SettingsHarnessTests(SenderHost host)
{
    [Fact]
    public async Task Фикстура_убирает_строку_оставленную_тестом()
    {
        await using (var _ = await SystemSettingsFixture.НачатьAsync(host))
        {
            await host.ЗаписатьМимоФикстурыAsync();
        }

        (await host.СтрокНастроекAsync(TestContext.Current.CancellationToken)).ShouldBe(0);
    }

    [Fact]
    public async Task Подмена_читателя_возвращается_после_фикстуры()
    {
        // ⚠ Зеркальный факт: без него первый доказывал бы только уборку таблиц. Оставленный
        // поднятым флаг «настоящие настройки» заражает не хуже строки — следующий тест
        // получит из базы не то, что задал подделкой, и покраснеет не по делу.
        await using (var _ = await SystemSettingsFixture.НачатьAsync(host))
        {
            host.НастоящиеНастройки.ShouldBeTrue();
        }

        host.НастоящиеНастройки.ShouldBeFalse();
    }
}
