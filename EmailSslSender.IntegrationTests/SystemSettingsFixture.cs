namespace EmailSslSender.IntegrationTests;

/// <summary>
/// Тест работает с НАСТОЯЩИМИ настройками и убирает за собой.
/// </summary>
/// <remarks>
/// ⚠ ⚠ <b>Заведено 2026-08-29 ДО первого теста, который пишет в общую таблицу настроек, а не
/// после.</b> Причина известна и стоила Python-версии полутора сотен красных тестов: пять строк,
/// оставленных живой проверкой в <c>system_settings</c>, уронили <b>151 тест</b>, которые этих
/// настроек не задавали. Среди строк была настроенная почта, а настроенная почта означает
/// обязательный код письмом при всяком входе. Увидеть причину можно было только полным прогоном,
/// а вылечилась она одной чисткой таблицы в общей обвязке — не правкой ста пятидесяти одного
/// теста.
///
/// ⚠ <b>Уборка живёт в фикстуре, а не в самом тесте.</b> Уборка внутри теста работает ровно до
/// первого падения посередине: она не выполнится, и заражённой окажется вся оставшаяся
/// коллекция — причём падать начнёт не тот тест, который наследил.
///
/// ⚠ <b>Та же коллекция <c>eams-host</c>, а не своя.</b> Коллекции xunit идут параллельно, и
/// чистка общей таблицы из соседней коллекции роняла бы чужой прогон непредсказуемо — хуже
/// того, невоспроизводимо.
///
/// ⚠ <b><c>user_preferences</c> заражает так же, только тише:</b> <c>ui.locale</c>, оставленный
/// чужим тестом, поменяет язык письма в тесте, который про язык ничего не знает. Поэтому
/// чистятся обе таблицы.
/// </remarks>
public sealed class SystemSettingsFixture(SenderHost host) : IAsyncDisposable
{
    /// <summary>Снять подмену и убрать всё, что осталось от прежних тестов.</summary>
    public static async Task<SystemSettingsFixture> НачатьAsync(SenderHost host)
    {
        ArgumentNullException.ThrowIfNull(host);

        await host.ОчиститьНастройкиAsync();
        host.НастоящиеНастройки = true;

        return new SystemSettingsFixture(host);
    }

    public async ValueTask DisposeAsync()
    {
        host.НастоящиеНастройки = false;
        await host.ОчиститьНастройкиAsync();
    }
}
