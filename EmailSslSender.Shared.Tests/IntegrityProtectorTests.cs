using System.Security.Cryptography;
using EmailSslSender.Shared.Crypto;

namespace EmailSslSender.Shared.Tests;

/// <summary>
/// Подпись значений ключом из мастер-ключа — на ней держатся хеши кодов входа.
/// </summary>
/// <remarks>
/// <b>Проверяется не «работает ли HMAC» — он работает.</b> Проверяется то, что легко
/// сделать неправильно и невозможно заметить по работающей системе: повторяема ли подпись
/// (иначе код не найдётся по хешу), покрывает ли она ключ записи и значение, различаются ли
/// назначения.
/// </remarks>
public sealed class IntegrityProtectorTests
{
    private const string Назначение = "identity.code.verifier";

    /// <summary>Одинаковый вход — одинаковый конверт: код ищется по хешу подписи.</summary>
    [Fact]
    public void Подпись_повторяема()
    {
        var сторож = Сторож(1);

        сторож.Protect(Назначение, "человек:login_code:", "123456")
            .ShouldBe(сторож.Protect(Назначение, "человек:login_code:", "123456"));
    }

    /// <summary>Конверт — версия, подпись и значение как есть.</summary>
    [Fact]
    public void Конверт_это_версия_подпись_значение()
    {
        var части = Сторож(1).Protect(Назначение, "ключ", "123456").Split('.');

        части.Length.ShouldBe(3);
        части[0].ShouldBe("1");
        части[1].Length.ShouldBe(43, "HMAC-SHA256 — 32 байта, в base64url без выравнивания 43 знака");
        части[2].ShouldBe("123456");
    }

    /// <summary>
    /// Годная подпись не переставляется на чужую запись.
    /// </summary>
    /// <remarks>
    /// ⚠ <b>Ради этого свойства ключ записи и входит в подпись.</b> Без него одинаковый код у
    /// двух людей давал бы одинаковый хеш, и строка одного находилась бы кодом другого.
    /// </remarks>
    [Fact]
    public void Подпись_зависит_от_ключа_записи()
    {
        var сторож = Сторож(1);

        Подпись(сторож.Protect(Назначение, "первый", "123456"))
            .ShouldNotBe(Подпись(сторож.Protect(Назначение, "второй", "123456")));
    }

    /// <summary>
    /// Ключ записи входит в подпись СОДЕРЖИМЫМ, а не длиной.
    /// </summary>
    /// <remarks>
    /// ⚠ <b>Тест дописан 2026-08-25 после мутации, которую сьют не поймал.</b> Мутация
    /// выбрасывала ключ записи из подписываемых байтов, оставляя на его месте нули, — и все
    /// проверки остались зелёными: ключи в тестах были <b>разной</b> длины, и подписи
    /// расходились по размеру, а не по содержимому. Здесь ключи одной длины.
    /// </remarks>
    [Fact]
    public void Ключи_одной_длины_не_взаимозаменяемы()
    {
        var сторож = Сторож(1);

        Подпись(сторож.Protect(Назначение, "ааа", "123456"))
            .ShouldNotBe(Подпись(сторож.Protect(Назначение, "ббб", "123456")));
    }

    /// <summary>
    /// Граница между ключом и значением однозначна.
    /// </summary>
    /// <remarks>
    /// ⚠ Без разделителя пара («ключ <c>ab</c>», «значение <c>c</c>») и пара («ключ
    /// <c>a</c>», «значение <c>bc</c>») дают одну подписываемую строку — то есть подпись
    /// переставляется между записями подбором границы. Тест ловит ровно это.
    /// </remarks>
    [Fact]
    public void Граница_ключа_и_значения_не_сдвигается()
    {
        var сторож = Сторож(1);

        Подпись(сторож.Protect(Назначение, "ab", "c"))
            .ShouldNotBe(Подпись(сторож.Protect(Назначение, "a", "bc")));
    }

    [Fact]
    public void Подпись_зависит_от_значения()
    {
        var сторож = Сторож(1);

        Подпись(сторож.Protect(Назначение, "ключ", "123456"))
            .ShouldNotBe(Подпись(сторож.Protect(Назначение, "ключ", "123457")));
    }

    /// <summary>Назначения не пересекаются: у каждого свой ключ подписи.</summary>
    [Fact]
    public void Назначения_не_пересекаются()
    {
        var сторож = Сторож(1);

        Подпись(сторож.Protect(Назначение, "ключ", "123456"))
            .ShouldNotBe(Подпись(сторож.Protect("другое.назначение", "ключ", "123456")));
    }

    /// <summary>Во время ротации подписывается уже действующая, то есть новая, версия.</summary>
    [Fact]
    public void Подписывается_действующая_версия()
    {
        var первый = Ключ();

        var до = new IntegrityProtector(
            MasterKeyRing.FromKeys(new Dictionary<int, byte[]> { [1] = первый }));
        var во_время = new IntegrityProtector(
            MasterKeyRing.FromKeys(new Dictionary<int, byte[]> { [1] = первый, [2] = Ключ() }));

        до.Protect(Назначение, "ключ", "123456").ShouldStartWith("1.");
        во_время.Protect(Назначение, "ключ", "123456").ShouldStartWith("2.");
    }

    /// <summary>Значение с точками внутри идёт в конверт как есть.</summary>
    [Fact]
    public void Точки_внутри_значения_безобидны()
    {
        Сторож(1).Protect(Назначение, "ключ", "1.2.3.4").ShouldEndWith(".1.2.3.4");
    }

    private static string Подпись(string конверт) => конверт.Split('.')[1];

    private static IntegrityProtector Сторож(int version) =>
        new(MasterKeyRing.FromKeys(new Dictionary<int, byte[]> { [version] = Ключ() }));

    private static byte[] Ключ() => RandomNumberGenerator.GetBytes(MasterKeyRing.KeyBytes);
}
