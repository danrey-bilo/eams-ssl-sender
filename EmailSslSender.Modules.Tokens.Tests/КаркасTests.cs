namespace EmailSslSender.Modules.Tokens.Tests;

/// <summary>
/// Каркас модуля собран и подключается (этап 10.5.2).
/// </summary>
/// <remarks>
/// ⚠ <b>Тестовому проекту нужен хотя бы один тест, и это не формальность.</b> Проект без
/// тестов собирается, запускается и отвечает «выполнено ноль» — то есть выглядит зелёным.
/// Пока модуль пуст, эта проверка — единственное, что доказывает: проект в решении есть,
/// раннер его находит, доступ к внутренностям через <c>InternalsVisibleTo</c> работает.
///
/// Настоящие проверки приезжают с подэтапа 10.5.3 вместе со схемой.
/// </remarks>
public sealed class КаркасTests
{
    [Fact]
    public void Точка_подключения_видна_снаружи()
    {
        // Наружу из сборки торчит ровно точка подключения и пространство Contracts —
        // это же проверяет ModuleSurface со стороны арх-тестов. Здесь — что она вообще есть.
        typeof(TokensModule).IsPublic.ShouldBeTrue();
    }

    [Fact]
    public void Тестовый_проект_видит_внутренности_своего_модуля()
    {
        // InternalsVisibleTo работает: тип internal виден. Без этого весь дальнейший сьют
        // писался бы через публичную поверхность, то есть заставлял бы её расширять.
        typeof(Api.InternalControllers).IsPublic.ShouldBeFalse();
    }
}
