using System.Net;
using EmailSslSender.Shared.Errors;

namespace EmailSslSender.Shared.Api;

/// <summary>
/// Размер страницы: одно правило на всю систему.
/// </summary>
/// <remarks>
/// ⚠ <b>Заведено 2026-08-28 по следу расхождения, а не «для порядка».</b> Четыре выдачи с
/// курсором решали вопрос «а если попросили тысячу» по-разному: журнал, люди и осиротевшие
/// хранилища <b>молча подрезали</b> до потолка, лента уведомлений <b>отвечала отказом</b>. Одна и
/// та же ошибка клиента давала на соседних адресах одного API два разных исхода — и узнать об
/// этом можно было только чтением четырёх файлов.
///
/// ⚠ <b>Выбрана СТРОГАЯ проверка, а не подрезание, и довод не «так аккуратнее».</b> Подрезание
/// безопасно ровно для того клиента, который следует курсору; а самый частый способ обратиться к
/// постраничной выдаче — попросить «сразу всё» одним большим числом и не читать `next_cursor`.
/// Такой клиент получает сотню строк из десяти тысяч и <b>считает, что это всё</b>. В менеджере
/// секретов это означает выгрузку, в которой молча нет девяноста девяти процентов записей.
///
/// Отказ стоит клиенту одной правки и сообщает, какой предел допустим; подрезание не стоит ничего
/// и не сообщает ничего.
///
/// ⚠ <b>Потолок остаётся у вызывающего.</b> Он разный по делу: лента — сотня, журнал и записи —
/// две сотни, и сводить их к одному числу значило бы решать за выдачи, которых ещё нет. Общее
/// здесь — <b>правило</b>, а не число.
///
/// ⚠ <b>Обойти это <c>Math.Clamp</c>'ом нельзя молча:</b> арх-проверка
/// <c>Eams.ArchTests/PagingLimits.cs</c> запрещает подрезать размер страницы где бы то ни было,
/// кроме этого файла.
/// </remarks>
public static class PageLimit
{
    /// <summary>
    /// Проверить запрошенный размер страницы.
    /// </summary>
    /// <param name="requested">Что попросил клиент. <c>null</c> — не просил ничего.</param>
    /// <param name="fallback">Сколько отдавать, если не просили.</param>
    /// <param name="max">Потолок этой выдачи.</param>
    /// <returns>Размер страницы.</returns>
    /// <exception cref="AppException">Запрошено вне <c>[1, max]</c> — <c>422</c>.</exception>
    public static int Require(int? requested, int fallback, int max)
    {
        if (fallback < 1 || fallback > max)
        {
            // Ошибка вызывающего, а не клиента: умолчание, не попадающее в собственный диапазон,
            // означает выдачу, которая отказывает на пустом запросе.
            throw new ArgumentOutOfRangeException(
                nameof(fallback), fallback, $"Умолчание вне допустимого: от 1 до {max}");
        }

        var сколько = requested ?? fallback;

        return сколько >= 1 && сколько <= max
            ? сколько
            : throw new AppException(
                ErrorCodes.Validation,
                $"Размер страницы вне допустимого: от 1 до {max}",
                HttpStatusCode.UnprocessableContent);
    }
}
