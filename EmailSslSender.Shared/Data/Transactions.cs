using Microsoft.EntityFrameworkCore;

namespace EmailSslSender.Shared.Data;

/// <summary>
/// Одна транзакция на действие — общая для всех модулей.
/// </summary>
/// <remarks>
/// <b>Почему здесь, а не по копии на модуль</b> — решение
/// <c>docs/decisions/0022-помощник-транзакций-в-shared.md</c>. Копий было три, четвёртая
/// назначалась планом хранилищ, и они <b>уже разъехались</b>. Мера правила 19 — «сколько
/// модулей сломается, если удалить» — даёт четыре, то есть самый ясный случай из возможных.
///
/// ⚠ Внутри модуля этот десяток строк тоже не размножается, и цена известна: до 2026-08-22 он
/// был написан <b>четырежды</b> в одном лишь модуле личностей — в службах людей, сессий, ролей
/// и команд, — и разъезжаться начал там же: одна копия несла разбор происходящего, три
/// остальные отсылали к ней комментарием «см. такой же помощник в UserService». Поправить одну
/// и забыть три — значит получить модуль, где половина действий защищена, а половина нет,
/// причём разницы не видно ни по одному тесту.
///
/// <b>Стратегия выполнения, а не голая транзакция.</b> Соединение с базой может оборваться,
/// и настроенная стратегия повторит делегат. Без неё повтор был бы запрещён самой EF: она
/// отказывается повторять то, что уже начало транзакцию, и падает с указанием обернуть
/// вызов ровно так.
///
/// ⚠ <b>Очистка трекера перед каждой попыткой обязательна.</b> Повтор выполняет делегат
/// заново, а добавленные первой попыткой сущности остаются отслеженными — вторая вставила бы
/// их <b>ещё раз</b>. Отсюда требование к телу: всё, что оно правит, оно и загружает —
/// внутри себя. Сущность, прочитанная до вызова, после очистки перестаёт отслеживаться, и
/// правки над ней уходят в никуда молча. Это уже случалось (активация учётной записи,
/// 2026-08-22) и было поймано тестом, а не чтением.
/// </remarks>
public static class Transactions
{
    /// <summary>Выполнить действие в транзакции, повторив при обрыве соединения.</summary>
    public static Task<T> InTransactionAsync<T>(
        this SenderDbContext db,
        Func<CancellationToken, Task<T>> action,
        CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(action);

        return db.InTransactionAsync((token, _) => action(token), cancellationToken);
    }

    /// <summary>
    /// То же, но с работой, которую надо сделать <b>после</b> фиксации.
    /// </summary>
    /// <remarks>
    /// ⚠ <b>Сброс кэша прав обязан идти после коммита, а не внутри него.</b> Внутри
    /// транзакции сдвиг версии — это заявление о намерении: изменение ещё не видно никому,
    /// кроме этой транзакции. Параллельный запрос того же человека в этот момент
    /// промахивается мимо кэша, читает из базы <b>ещё не изменённые</b> права и кладёт их под
    /// <b>уже новой</b> версией. Транзакция фиксируется — а в кэше лежит устаревший профиль
    /// под актуальным ключом, и живёт он до конца срока хранения, то есть сутки. Отобранное
    /// право продолжает работать. Найдено разбором 2026-08-22; ровно то окно, ради отсутствия
    /// которого версия и выбрана вместо срока жизни.
    ///
    /// А если транзакция откатится, сброс не случится вовсе — и правильно: сбрасывать нечего,
    /// права не менялись.
    ///
    /// <b>Очередь очищается перед каждой попыткой</b> по той же причине, что и трекер: повтор
    /// выполняет тело заново и записал бы работу дважды.
    /// </remarks>
    public static async Task<T> InTransactionAsync<T>(
        this SenderDbContext db,
        Func<CancellationToken, AfterCommit, Task<T>> action,
        CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(db);
        ArgumentNullException.ThrowIfNull(action);

        var after = new AfterCommit();

        // ⚠ Транзакция вызывающего уважается, а не подменяется. Службы модуля зовут друг
        // друга, а с появлением контракта выдачи доступа их зовёт ещё и СОСЕД — из своей
        // транзакции, вокруг своей записи. Открой мы здесь вторую, EF отказал бы; а очистка
        // трекера выбросила бы всё, что сосед успел набрать до вызова, — молча и без единой
        // ошибки. Найдено разбором готовности 2026-08-24.
        if (db.Database.CurrentTransaction is not null)
        {
            if (!after.Empty)
            {
                // Сюда не попасть иначе как ошибкой: очередь заполняется телом, а тело ещё не
                // выполнялось. Проверка стоит после вызова.
                throw new InvalidOperationException("Очередь «после фиксации» уже не пуста");
            }

            var nested = await action(cancellationToken, after);

            if (!after.Empty)
            {
                // Фиксировать будет вызывающий, и когда — нам неизвестно. Выполнить
                // отложенное сейчас значило бы сделать его до фиксации, то есть ровно то, от
                // чего очередь и защищает; отложить «на потом» некуда.
                throw new InvalidOperationException(
                    "Действие внутри чужой транзакции отложило работу на фиксацию, а фиксирует "
                    + "не оно. Либо действие зовётся своей транзакцией, либо работа делается "
                    + "не через очередь.");
            }

            return nested;
        }

        var result = await db.Database.CreateExecutionStrategy().ExecuteAsync(
            cancellationToken,
            async (token) =>
            {
                db.ChangeTracker.Clear();
                after.Forget();

                await using var transaction = await db.Database.BeginTransactionAsync(token);

                var attempt = await action(token, after);

                await transaction.CommitAsync(token);

                return attempt;
            });

        // ⚠ ⚠ ⚠ ОТЛОЖЕННОЕ — ЗА ПРЕДЕЛАМИ СТРАТЕГИИ, И ЭТО НЕСУЩЕЕ (ревью 2026-09-15, data-1).
        // Прежде очередь выполнялась ВНУТРИ делегата, сразу после `CommitAsync`. Стратегия
        // Npgsql считает временным сбоем любой `TimeoutException`, а отложенное действие
        // (в EAMS — публикация в подвисший кэш) бросало именно его и заставляло стратегию
        // повторить УЖЕ ЗАФИКСИРОВАННУЮ транзакцию — очистить трекер, завести новое сообщение
        // с новым Guid и зафиксировать ещё раз. До четырёх одинаковых сообщений и 500 человеку,
        // который отправлял одно.
        //
        // Здесь очередь выполняется ОДИН раз и принадлежит последней, успешной попытке: каждая
        // попытка начинается с `Forget`, так что работа неудавшихся до сюда не доживает.
        //
        // ⚠ Токен отмены — `None`. Транзакция уже состоялась; отмена запроса в эту минуту
        // означала бы ошибку на записанном действии, и человек повторил бы его.
        //
        // мутация 2026-09-15: вернул вызов очереди внутрь делегата после `CommitAsync` →
        // покраснел AfterCommitRetryApi.Таймаут_после_фиксации_не_повторяет_транзакцию.
        await after.RunAsync(CancellationToken.None);

        return result;
    }

    /// <summary>То же для действия без результата.</summary>
    public static async Task InTransactionAsync(
        this SenderDbContext db,
        Func<CancellationToken, Task> action,
        CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(action);

        await db.InTransactionAsync<bool>(
            async (token) =>
            {
                await action(token);

                return true;
            },
            cancellationToken);
    }
}

/// <summary>
/// Работа, которую надо сделать, когда транзакция уже состоялась.
/// </summary>
/// <remarks>
/// Сюда попадает то, что <b>нельзя откатить</b> и потому нельзя делать раньше времени:
/// сегодня это сброс кэша прав, завтра — оповещение или отправка письма. Общее у всего этого
/// одно: если транзакция не закрепится, делать этого не надо было вовсе.
/// </remarks>
public sealed class AfterCommit
{
    private readonly List<Func<CancellationToken, Task>> queued = [];

    /// <summary>Отложить работу до фиксации.</summary>
    public void Then(Func<CancellationToken, Task> work) => queued.Add(work);

    /// <summary>Ничего не отложено.</summary>
    internal bool Empty => queued.Count == 0;

    /// <summary>Забыть отложенное: попытка не удалась и начинается заново.</summary>
    internal void Forget() => queued.Clear();

    /// <summary>Сделать отложенное. Порядок — тот, в котором откладывали.</summary>
    /// <remarks>
    /// ⚠ <b>Сбой одной работы не отменяет следующих</b> (ревью 2026-09-15). Сброс кэша прав,
    /// отложенный после неудавшейся публикации кадра, обязан выполниться: иначе отобранное
    /// право продолжило бы работать из-за сбоя в совсем другом месте. Ошибка выбрасывается
    /// <b>после</b> всех работ — единственная как есть, несколько — одним
    /// <c>AggregateException</c>; громко, но уже без повтора транзакции: вызов стоит вне
    /// стратегии выполнения.
    /// </remarks>
    internal async Task RunAsync(CancellationToken cancellationToken)
    {
        List<Exception>? errors = null;

        foreach (var work in queued)
        {
            try
            {
                await work(cancellationToken);
            }
            catch (Exception error)
            {
                (errors ??= []).Add(error);
            }
        }

        if (errors is null)
        {
            return;
        }

        if (errors.Count == 1)
        {
            System.Runtime.ExceptionServices.ExceptionDispatchInfo.Throw(errors[0]);
        }

        throw new AggregateException("Работа после фиксации не удалась", errors);
    }
}
