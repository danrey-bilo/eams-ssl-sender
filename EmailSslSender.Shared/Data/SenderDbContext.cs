using EmailSslSender.Shared.Contracts.Data;
using Microsoft.EntityFrameworkCore;

namespace EmailSslSender.Shared.Data;

/// <summary>
/// Единственный контекст базы данных на всю систему.
/// </summary>
/// <remarks>
/// <b>Один контекст, а не по контексту на модуль</b> — осознанное отступление от канона
/// модульного монолита, и вот его причина. Аудит и квоты режут систему поперёк: создание
/// записи в хранилище — одна транзакция, которая трогает таблицу записей, счётчик квоты и
/// кладёт строку в журнал. С отдельными контекстами каждая такая операция стала бы
/// распределённой транзакцией внутри одного процесса: общее подключение, ручной
/// <c>UseTransaction</c>, порядок сохранения между контекстами. Сложность на ровном месте,
/// и вся она — ради чистоты, которой всё равно не будет: база-то одна.
///
/// А требование атомарности здесь не пожелание. «Не сохранилась строка аудита — не должно
/// состояться и действие»: секрет, показанный без следа в журнале, хуже, чем не показанный
/// вовсе.
///
/// <b>Граница модулей при этом не размывается.</b> Контекст не знает ни одной сущности —
/// он собирает <see cref="IEntityConfigurationProvider"/>, а объявляют их модули у себя.
/// Кто чем владеет, проверяет архитектурный тест, а не память.
///
/// <b>Почему это не нарушает правило 19</b> («в <c>Shared</c> нет <c>DbContext</c>»). Правило
/// написано против <i>чужого</i> контекста в общей библиотеке — против того, чтобы модуль
/// тащил в <c>Shared</c> своё хранилище. Здесь наоборот: контекст пуст и знает только
/// контракт. Формулировка правила уточнена в <c>RULES.md</c> вместе с этим кодом.
/// </remarks>
public sealed class SenderDbContext(
    DbContextOptions<SenderDbContext> options,
    IEnumerable<IEntityConfigurationProvider> configurations)
    : DbContext(options)
{
    /// <summary>
    /// Чем этот контекст отличается от другого того же типа: набор конфигураций модулей.
    /// </summary>
    /// <remarks>
    /// ⚠ ⚠ <b>Нужен ключу кэша модели, и заведён по следу дефекта</b> (подэтап 27.4). EF
    /// кэширует модель по ТИПУ контекста, а наша модель зависит от содержимого контейнера —
    /// то есть от того, чего ключ по умолчанию не видит. Два контекста одного типа с разными
    /// наборами делили одну модель, и приложение получало пустую, если обвязка успела
    /// раньше. Разбор — <see cref="SenderModelCacheKeyFactory"/>.
    ///
    /// ⚠ Считается ОДИН раз: набор внедряется конструктором и за жизнь контекста не меняется,
    /// а ключ спрашивают на каждом построении модели.
    /// </remarks>
    internal string ConfigurationKey { get; } = string.Join(
        '\n',
        configurations.Select(провайдер => провайдер.GetType().FullName).Order(StringComparer.Ordinal));

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        base.OnModelCreating(modelBuilder);

        foreach (var configuration in configurations)
        {
            configuration.Configure(modelBuilder);
        }
    }
}
