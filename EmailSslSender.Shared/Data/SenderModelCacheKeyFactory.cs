using EmailSslSender.Shared.Contracts.Data;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;

namespace EmailSslSender.Shared.Data;

/// <summary>
/// Ключ кэша модели, учитывающий набор конфигураций модулей.
/// </summary>
/// <remarks>
/// ⚠ ⚠ <b>Заведён по следу настоящего дефекта</b> (подэтап 27.4, первый прогон CI на ветке
/// этапов 28–33: 721 сбой из 751 при зелёном локальном прогоне).
///
/// EF Core кэширует построенную модель, и ключом по умолчанию служит
/// <b>тип контекста</b> плюс признак «время разработки». Для обычного контекста этого
/// довольно: его модель задана его же кодом. Но модель <see cref="SenderDbContext"/> собирается
/// из внедрённых <see cref="IEntityConfigurationProvider"/> — то есть <b>зависит от
/// содержимого контейнера, о котором ключ по умолчанию не знает ничего</b>. Два контекста
/// одного типа с разными наборами конфигураций делили одну модель, и доставалась она тому,
/// кто построил её первым.
///
/// Чем это кончилось: обвязка тестов поднимала контекст без конфигураций модулей (миграции —
/// классы сборки хоста, модель для них не нужна), выигрывала гонку, и настоящее приложение
/// в том же процессе получало <b>пустую модель</b>. Дальше краснело всё сразу:
/// <c>HasPendingModelChanges()</c> отвечал «модель разошлась с миграциями», а сеятель прав не
/// находил своей таблицы. Исход решал порядок классов внутри прогона — потому локально было
/// зелено, а в CI красно.
///
/// ⚠ <b>Это цена именованного исключения правила 19</b> («контекст не знает ни одной
/// сущности»). Решение остаётся верным: оно и держит границы модулей. Но у него есть
/// следствие, и до 27.4 оно нигде не было названо — а молчаливое следствие однажды
/// становится дефектом.
///
/// ⚠ <b>Ключ строится по ТИПАМ провайдеров, а не по их числу.</b> Число совпадает у разных
/// наборов слишком легко: два модуля местами — тот же счёт, другая модель. Порядок при этом
/// не важен (набор, а не список), поэтому имена сортируются.
/// </remarks>
public sealed class SenderModelCacheKeyFactory : IModelCacheKeyFactory
{
    /// <inheritdoc />
    public object Create(DbContext context, bool designTime)
    {
        ArgumentNullException.ThrowIfNull(context);

        // Чужой контекст ключуется как обычно: подменять поведение для всех — не наше дело.
        var набор = context is SenderDbContext наш ? наш.ConfigurationKey : string.Empty;

        return (context.GetType(), набор, designTime);
    }
}
