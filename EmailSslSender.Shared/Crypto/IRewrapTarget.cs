namespace EmailSslSender.Shared.Crypto;

/// <summary>Сколько обёрток пересмотрено, сколько переложено и откуда продолжать.</summary>
/// <param name="Seen">Сколько строк посмотрели.</param>
/// <param name="Rewrapped">Сколько переложили. Остальные уже были под действующей версией.</param>
/// <param name="Next">
/// Откуда продолжать. <c>null</c> — дошли до конца.
///
/// ⚠ <b>Курсор нужен, потому что отобрать «нуждающиеся» запросом нельзя.</b> Версия ключа
/// лежит внутри байтов обёртки, а не отдельной колонкой: в SQL по ней не отфильтровать, и
/// узнать, нужно ли перекладывать, можно только прочитав строку. Без курсора каждый вызов
/// начинал бы просмотр сначала — на таблице в миллион строк это превращает проход в
/// квадрат. Отдельной колонки с версией нет намеренно: она была бы вторым источником правды
/// о том, что и так записано в самой обёртке.
/// </param>
public readonly record struct RewrapBatch(int Seen, int Rewrapped, string? Next);

/// <summary>
/// Модуль перекладывает своё запечатанное под действующую версию мастер-ключа.
/// </summary>
/// <remarks>
/// <b>Зачем это в общей библиотеке.</b> Кольцо ключей и конверт умеют главное — держать
/// несколько версий сразу и переложить обёртку под новую (<c>NeedsRewrap</c> и
/// <c>Rewrap</c>). Чего они не умеют и уметь не могут: <b>найти</b> запечатанное. Оно лежит в
/// таблицах модулей, и знает о них только владелец. Без этого контракта ротацию пришлось бы
/// писать в общем месте со знанием всех чужих таблиц — то есть ровно так, как устроена
/// Python-версия и от чего этот перенос уходит.
///
/// ⚠ <b>Ротация без перекладывания — половина дела, и худшая.</b> Дописать в кольцо новую
/// версию можно и сейчас: свежие секреты запечатываются ею, старые по-прежнему открываются
/// прежней. Но <b>выбросить прежнюю нельзя</b> — а именно ради этого ротацию и делают: ключ,
/// который нельзя вывести из обращения, после утечки остаётся полезным навсегда. Найдено
/// разбором готовности 2026-08-24: документация описывала ротацию как готовую, а перебрать
/// запечатанное было нечем.
///
/// ⚠ <b>Перекладывается обёртка, а не данные.</b> Мастер-ключ не шифрует секреты никогда — он
/// оборачивает ключи данных. Поэтому смена ключа не трогает ни одного шифротекста, и
/// перекладывание безопасно повторять: сорвалось на середине — следующий проход доделает.
///
/// <b>Порциями и с продолжением.</b> Метод зовут, пока он возвращает курсор. Так проход не
/// держит одну длинную транзакцию на всю таблицу и переживает обрыв: сделанное уже
/// зафиксировано, а начатый заново проход просто пропустит то, что уже переложено.
/// </remarks>
public interface IRewrapTarget
{
    /// <summary>Что перекладываем — для строки в журнале и в логе. Обычно имя таблицы.</summary>
    string Name { get; }

    /// <summary>
    /// Переложить очередную порцию.
    /// </summary>
    /// <remarks>
    /// ⚠ <b>Реализация обязана быть идемпотентной.</b> Строка, уже лежащая под действующей
    /// версией, пропускается — иначе повторный запуск после обрыва переложил бы всё заново,
    /// а «переложить заново» это перезапись столбца с ключом: сбой посреди такой перезаписи
    /// стоит секрета.
    /// </remarks>
    /// <param name="batch">Сколько строк взять за раз.</param>
    /// <param name="after">Откуда продолжать. <c>null</c> — с начала.</param>
    /// <param name="cancellationToken">Отмена.</param>
    Task<RewrapBatch> RewrapAsync(
        int batch, string? after = null, CancellationToken cancellationToken = default);
}
