namespace EmailSslSender.Shared.Crypto;

/// <summary>
/// Привязка секрета, заданного до привязки к адресу, — к адресу из текущих настроек.
/// </summary>
/// <remarks>
/// ⚠ ⚠ <b>Исполняет только команда <c>migrate</c></b> (ревью безопасности 2026-10-20). Прежде
/// старый секрет привязывался к адресу первого использования — а первым мог оказаться
/// захвативший сессию: сменил адрес сервера на свой, нажал «Проверить», и секрет уходил ему.
/// Консоль установки — доверенное место, сессия панели — нет; во время работы секрет без
/// привязки не открывается вовсе.
/// </remarks>
public interface ILegacySecretBinder
{
    /// <summary>Что привязывается — словами для вывода команды.</summary>
    string Name { get; }

    /// <summary>Привязать, если секрет есть и ещё без привязки.</summary>
    /// <returns><c>true</c> — привязан сейчас; <c>false</c> — нечего привязывать.</returns>
    Task<bool> BindAsync(CancellationToken cancellationToken = default);
}
