namespace EmailSslSender.Shared.Crypto;

/// <summary>
/// Подпись значения ключом, выведенным из мастер-ключа (HMAC-SHA256).
/// </summary>
/// <remarks>
/// <b>Зачем это есть.</b> Шестизначный код входа слишком короток, чтобы хранить его голым
/// хешем: по дампу базы его перебирают за секунды. Подпись ключом, которого в базе нет, делает
/// такой перебор бесполезным без мастер-ключа — хешируется уже подписанное значение
/// (<c>Invitations.CodeHash</c>).
///
/// ⚠ <b>Подпись покрывает и значение, и ключ записи.</b> Без ключа записи одинаковый код
/// давал бы одинаковую подпись у разных людей и назначений.
///
/// ⚠ <b>Своё назначение у каждого потребителя.</b> Ключ подписи выводится из мастер-ключа
/// через HKDF с назначением в качестве информации: разные назначения получают разные ключи.
///
/// <b>Чего этот контракт НЕ делает.</b> Не шифрует: подпись говорит «это писали мы», а не
/// «этого никто не прочтёт». Для секретов есть <see cref="ISecretEnvelope"/>.
/// </remarks>
public interface IIntegrityProtector
{
    /// <summary>Подписать значение.</summary>
    /// <param name="purpose">
    /// Кто подписывает, например <c>identity.code.verifier</c>. Входит в вывод ключа, поэтому
    /// меняться у одного потребителя не должен — сменившееся назначение обесценивает все прежние
    /// подписи разом.
    /// </param>
    /// <param name="recordKey">Ключ записи. Входит в подпись.</param>
    /// <param name="value">Само значение.</param>
    /// <returns>
    /// Конверт: версия ключа, подпись, значение. Для одного и того же входа при той же
    /// действующей версии мастер-ключа — всегда один и тот же.
    /// </returns>
    string Protect(string purpose, string recordKey, string value);
}
