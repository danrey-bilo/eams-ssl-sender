namespace EmailSslSender.Shared.Crypto;

/// <summary>
/// Что сказала проверка подписи значения, пришедшего из недоверенного хранилища.
/// </summary>
/// <remarks>
/// ⚠ <b>Три исхода, а не два, и третий — не педантизм.</b> «Подпись не сошлась» и «подписи
/// нашего ключа тут нет» означают разное: первое — событие безопасности, второе — обычное
/// последствие ротации мастер-ключа. Свести их в один — значит либо поднимать тревогу
/// после каждой ротации (и научить людей её игнорировать), либо не поднимать никогда.
/// </remarks>
public enum IntegrityVerdict
{
    /// <summary>Подпись сошлась. Значению можно верить ровно настолько, насколько ключу.</summary>
    Ok,

    /// <summary>
    /// Значение подделано: разобрать не удалось либо подпись не сошлась при <b>известном</b>
    /// ключе.
    /// </summary>
    /// <remarks>
    /// Это <b>событие безопасности</b>, а не промах кэша. Протухнуть значение может;
    /// подделаться случайно — нет. Обязанности вызывающего: принять решение по базе,
    /// написать строку в журнал, поднять тревогу.
    /// </remarks>
    Tampered,

    /// <summary>
    /// Подписано ключом, которого в ринге нет. Промах, а не тревога.
    /// </summary>
    /// <remarks>
    /// Так выглядит значение, пережившее ротацию мастер-ключа: прежняя версия ушла из
    /// ринга, и проверить подпись больше нечем. ⚠ Так же выглядит и мусор с выдуманным
    /// номером версии — и это <b>принятая</b> слабость: подделать значение таким способом
    /// нельзя, можно лишь вызвать промах, то есть замедлить систему, оставив её правильной.
    /// </remarks>
    Foreign,
}

/// <summary>
/// Подпись значений, живущих <b>вне процесса</b>: кэшей, счётчиков, зеркал, очередей.
/// </summary>
/// <remarks>
/// <b>Зачем это вообще есть (правило 23, решение 0006).</b> Всё, что живёт вне процесса и
/// участвует в решении о доступе, недоверенно. Ключ записи вычисляется детерминированно,
/// формат виден из исходника — «до кэша не дотянуться» есть свойство сети, а не программы,
/// и любая ошибка в самой программе обходит его целиком. Кто может писать в такое
/// хранилище, тот назначает любому человеку любые права — если значение не подписано.
///
/// ⚠ <b>Подпись покрывает и значение, и ключ записи.</b> Без ключа годную подпись
/// переставляют с чужой записи на свою: профиль прав администратора, переписанный на ключ
/// обычного человека, — совершенно законная подпись и полный набор прав.
///
/// ⚠ <b>Своё назначение у каждого потребителя.</b> Ключ подписи выводится из мастер-ключа
/// через HKDF с назначением в качестве информации: кэш прав и кэш настроек подписываются
/// <b>разными</b> ключами. Иначе значение, годное в одном хранилище, окажется годным и в
/// другом — а форматы у них разные, и что из этого выйдет, предсказать нельзя.
///
/// <b>Чего этот контракт НЕ делает.</b> Не шифрует: подпись говорит «это писали мы», а не
/// «этого никто не прочтёт». Содержимое кэша прав не секрет — секретны сами секреты, и для
/// них есть <see cref="ISecretEnvelope"/>. Не хранит: где лежит значение, знает вызывающий.
/// </remarks>
public interface IIntegrityProtector
{
    /// <summary>Подписать значение перед отправкой наружу.</summary>
    /// <param name="purpose">
    /// Кто подписывает: <c>authz-cache</c>, <c>settings-cache</c>. Входит в вывод ключа,
    /// поэтому меняться у одного потребителя не должен — сменившееся назначение
    /// обесценивает все прежние записи разом.
    /// </param>
    /// <param name="recordKey">Ключ записи в хранилище. Входит в подпись.</param>
    /// <param name="value">Само значение.</param>
    /// <returns>Конверт: версия ключа, подпись, значение.</returns>
    string Protect(string purpose, string recordKey, string value);

    /// <summary>Проверить конверт и достать значение.</summary>
    /// <param name="purpose">Тот же, с которым подписывали. Другой даст другой ключ.</param>
    /// <param name="recordKey">Ключ записи, под которым значение лежало.</param>
    /// <param name="envelope">Прочитанное из хранилища.</param>
    /// <param name="value">
    /// Значение — только при <see cref="IntegrityVerdict.Ok"/>. В остальных случаях
    /// <c>null</c>: отдать «подозрительное, но, может, сойдёт» — это ровно то, ради
    /// предотвращения чего написан весь контракт.
    /// </param>
    IntegrityVerdict TryUnprotect(string purpose, string recordKey, string envelope, out string? value);
}
