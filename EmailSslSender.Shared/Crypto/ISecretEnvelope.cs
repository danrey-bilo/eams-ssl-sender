namespace EmailSslSender.Shared.Crypto;

/// <summary>
/// Ключ данных, обёрнутый мастер-ключом. В базе живёт только в таком виде.
/// </summary>
/// <remarks>
/// Отдельный тип, а не <c>byte[]</c>, ради одной-единственной ошибки, которую он делает
/// невозможной: передать запечатанный секрет туда, где ждут ключ. Оба — массивы байтов, оба
/// приходят из одной таблицы, и перепутать их местами при рефакторинге легче лёгкого.
/// Компилятор ловит это бесплатно.
/// </remarks>
/// <param name="bytes">Обёрнутый ключ: заголовок, nonce, тег, шифротекст.</param>
public readonly struct WrappedDataKey(byte[] bytes)
{
    /// <summary>Байты для хранения. Секретом не являются — ключ внутри зашифрован.</summary>
    public byte[] Bytes { get; } = bytes;

    /// <summary>Содержимое не печатается: привычка важнее того, что внутри шифротекст.</summary>
    public override string ToString() => "<обёрнутый ключ данных>";
}

/// <summary>
/// Запечатанный секрет: шифротекст вместе со всем, что нужно его открыть, кроме ключа.
/// </summary>
/// <param name="bytes">Заголовок, nonce, тег, шифротекст — одним значением для одной колонки.</param>
public readonly struct SealedSecret(byte[] bytes)
{
    /// <summary>Байты для хранения.</summary>
    public byte[] Bytes { get; } = bytes;

    /// <summary>Содержимое не печатается.</summary>
    public override string ToString() => "<запечатанный секрет>";
}

/// <summary>
/// Конверт секретов: мастер-ключ оборачивает ключи данных, ключи данных шифруют секреты.
/// </summary>
/// <remarks>
/// <b>Зачем два уровня.</b> Шифруй мы всё мастер-ключом напрямую, его смена означала бы
/// перешифровку каждого секрета в установке — часы работы и окно, в котором часть данных
/// уже новая, часть ещё старая. С конвертом смена мастер-ключа трогает только обёртки
/// ключей: их столько, сколько хранилищ, а не столько, сколько паролей. И наоборот:
/// компрометация одного ключа данных стоит одного хранилища, а не всех.
///
/// <b>Привязка к месту (<c>context</c>) — не украшение.</b> Каждое запечатывание связано со
/// строкой, говорящей, чей это секрет и какое поле: <c>"user:{id}:totp_seed"</c>. Она уходит
/// в AEAD как связанные данные, и это значит, что шифротекст, скопированный в чужую строку
/// или в соседнюю колонку, <b>не откроется</b>. Без привязки тот, у кого есть запись в базу
/// (но не ключи), переставляет чужой секрет к себе и получает его в открытом виде обычным
/// показом. Добавить это потом нельзя: у всех уже записанных секретов связанных данных не
/// будет, и открыть их станет нечем.
///
/// ⚠ <b>Открытый секрет живёт в <c>byte[]</c>, а не в <c>string</c>.</b> Массив можно
/// затереть <c>CryptographicOperations.ZeroMemory</c>, строку — нет: она неизменяема, лежит
/// в куче и уезжает в дамп памяти целиком. Текстовые перегрузки здесь есть, но каждая из них
/// — осознанная уступка удобству, и в её описании это сказано прямо.
/// </remarks>
public interface ISecretEnvelope
{
    /// <summary>Завести новый ключ данных, уже обёрнутый действующим мастер-ключом.</summary>
    /// <param name="generation">
    /// Поколение ключа данных. Меняется, когда ключ хранилища перевыпускают, — тогда старые
    /// секреты остаются на прежнем поколении, пока их не перешифруют.
    /// </param>
    WrappedDataKey CreateDataKey(int generation = 1);

    /// <summary>Запечатать секрет ключом данных.</summary>
    /// <param name="key">Обёрнутый ключ владельца секрета.</param>
    /// <param name="plaintext">Что прячем.</param>
    /// <param name="context">Чей это секрет и какое поле. Уходит в связанные данные AEAD.</param>
    SealedSecret Seal(WrappedDataKey key, ReadOnlySpan<byte> plaintext, string context);

    /// <summary>Открыть секрет. Вызывающий обязан затереть результат, когда он больше не нужен.</summary>
    /// <exception cref="System.Security.Cryptography.CryptographicException">
    /// Ключ не тот, контекст не тот, данные подменены или поколение ключа не совпало.
    /// </exception>
    byte[] Open(WrappedDataKey key, SealedSecret secret, string context);

    /// <summary>Запечатать текст. UTF-8; исходную строку затереть нечем — см. замечание к типу.</summary>
    SealedSecret SealText(WrappedDataKey key, string plaintext, string context);

    /// <summary>Открыть текст. Результат затереть нечем — см. замечание к типу.</summary>
    string OpenText(WrappedDataKey key, SealedSecret secret, string context);

    /// <summary>Обёрнут ли ключ не действующим мастер-ключом — то есть ждёт ли ротации.</summary>
    bool NeedsRewrap(WrappedDataKey key);

    /// <summary>
    /// Перевернуть обёртку на действующий мастер-ключ.
    /// </summary>
    /// <remarks>
    /// Ключ данных при этом <b>не меняется</b>, поэтому перешифровывать секреты не нужно —
    /// ради этого свойства конверт и существует.
    /// </remarks>
    WrappedDataKey Rewrap(WrappedDataKey key);

}
