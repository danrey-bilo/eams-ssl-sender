using Microsoft.EntityFrameworkCore;

namespace EmailSslSender.Shared.Contracts.Data;

/// <summary>
/// Модуль приносит конфигурации своих сущностей в общую модель.
/// </summary>
/// <remarks>
/// Точка расширения того же рода, что объявление пермишенов: общий контекст не знает, какие
/// таблицы у модулей, — он лишь собирает то, что они объявили. Добавление модуля не
/// требует правки ни в контексте, ни в хосте.
///
/// Сущности при этом остаются <c>internal</c>: <c>ModelBuilder.Entity&lt;T&gt;()</c>
/// работает с внутренними типами, потому что реализация провайдера живёт в той же сборке,
/// что и сущность.
///
/// <b>Почему сканирование сборки не годится.</b> <c>ApplyConfigurationsFromAssembly</c>
/// нашёл бы внутренние конфигурации только по стечению обстоятельств в поведении
/// рефлексии, а молчаливо пропущенная конфигурация означает таблицу, которой нет в
/// миграции. Явная регистрация ломается громко.
/// </remarks>
public interface IEntityConfigurationProvider
{
    /// <summary>Описать свои сущности в общей модели.</summary>
    void Configure(ModelBuilder modelBuilder);
}
