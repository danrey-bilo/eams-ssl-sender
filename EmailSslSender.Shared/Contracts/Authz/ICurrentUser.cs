using EmailSslSender.Shared.Contracts.Audit;

namespace EmailSslSender.Shared.Contracts.Authz;

/// <summary>
/// Кто пришёл с этим запросом.
/// </summary>
/// <remarks>
/// Живёт в общей библиотеке, а не в модуле личностей: спросить «кто это» нужно всем, а
/// ссылаться на чужой модуль нельзя никому.
///
/// ⚠ <b>Признака «суперпользователь» здесь нет, и это решение, а не пропуск.</b> В этой
/// установке ролей и прав нет: каждая учётная запись — администратор с полным доступом.
/// Признак, который у всех одинаков, ничего не различает и однажды начал бы что-то значить
/// по ошибке.
/// </remarks>
public interface ICurrentUser
{
    /// <summary>Идентификатор или <c>null</c>, если запрос неаутентифицирован.</summary>
    Guid? Id { get; }

    /// <summary>Человек или сама система (фоновые задачи, консольные команды).</summary>
    AuditActorType ActorType { get; }

    /// <summary>
    /// Какой сессией пришли.
    /// </summary>
    /// <remarks>
    /// Нужен действиям человека над собой: выйти из этой сессии, сменить пароль, оставив её
    /// живой, отметить её в списке «где я вошёл» как текущую.
    /// </remarks>
    Guid? SessionId => null;

    /// <summary>
    /// Системе нужно, чтобы этот человек сменил пароль, — и до тех пор он ограничен.
    /// </summary>
    /// <remarks>
    /// Ставится при заведении учётной записи с паролем, выданным администратором. Ограничение
    /// живёт в конвейере хоста (<c>AuthenticationFilter</c>): с ним открыты только вход, выход
    /// и смена пароля.
    /// </remarks>
    bool MustChangePassword => false;

    /// <summary>
    /// Системе нужно, чтобы этот человек подключил второй фактор, — и до тех пор он ограничен.
    /// </summary>
    /// <remarks>
    /// Второе ограничение того же рода, что и требование сменить пароль, и устроено так же:
    /// проверяется в конвейере, а исключения объявлены пометкой
    /// <see cref="AllowWhileTwoFactorEnrollmentRequiredAttribute"/> на эндпоинтах.
    /// </remarks>
    bool MustEnrollTwoFactor => false;

    /// <summary>
    /// Когда личность подтверждали последний раз — на <b>этом</b> предъявленном токене.
    /// </summary>
    /// <remarks>
    /// ⚠ <b>На токене, а не на человеке.</b> Отметка на человеке означала бы, что
    /// переподтверждение в одной вкладке открывает опасные действия <b>во всех</b> его сессиях,
    /// а украденная живая сессия начинает работать оттого, что законный владелец ввёл код у себя.
    ///
    /// ⚠ <b>Умолчание — <c>null</c>, то есть «не подтверждали».</b>
    ///
    /// Сколько отметка считается свежей, решает не она, а <see cref="IStepUpFreshness"/>: окно —
    /// настройка, и записанный сюда срок разошёлся бы с ней при первой же правке.
    /// </remarks>
    DateTimeOffset? StepUpAt => null;
}
