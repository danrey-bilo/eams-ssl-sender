namespace EmailSslSender.Shared.Contracts.Authz;

/// <summary>
/// Действие требует свежего второго фактора: кода из приложения, подтверждённого в ЭТОЙ сессии
/// не раньше чем <c>auth.step_up_minutes</c> минут назад (по умолчанию десять).
/// </summary>
/// <remarks>
/// ⚠ ⚠ <b>Решение владельца 2026-10-20, заменившее «второй фактор — только при входе».</b> Каждая
/// учётная запись — администратор, раздающий закрытые ключи, и живая сессия, оставленная в чужих
/// руках, давала бы их все без единого вопроса. Помечаются действия, после которых установку не
/// узнать или которые отдают ключи: ключ API Key Manager Plus и выгрузка сертификатов, подписки,
/// пароль SMTP, управление людьми.
///
/// ⚠ <b>Вход с кодом уже считается свежим подтверждением:</b> отметка ставится на токен при входе,
/// и первые минуты после него вопросов нет. Дальше — <c>POST /api/me/step-up</c> с кодом.
///
/// Проверяет фильтр хоста через <see cref="IStepUpFreshness"/> — после ограничений личности (смена
/// пароля, подключение фактора). Отказ — <c>403 SECOND_FACTOR_REQUIRED</c> с
/// <c>details.window_minutes</c>.
///
/// ⚠ <b>Правку настроек атрибутом не пометить:</b> свежий фактор нужен ей только для ключей защиты
/// (<see cref="Settings.ISettingDeclaration.IsSecurity"/>), а какие ключи пришли, видно лишь из
/// тела. Её проверяет служба настроек сама, тем же контрактом.
/// </remarks>
[AttributeUsage(AttributeTargets.Method)]
public sealed class RequireRecentSecondFactorAttribute : Attribute;
