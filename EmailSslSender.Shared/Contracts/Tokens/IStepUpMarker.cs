namespace EmailSslSender.Shared.Contracts.Tokens;

/// <summary>
/// Отметить предъявленный токен как переподтверждённый.
/// </summary>
/// <remarks>
/// <b>Зачем отдельный контракт, а не третий метод у соседей.</b> У <see cref="ITokenIssuer"/>
/// обязанность выдавать, у <see cref="ITokenRevoker"/> — гасить; «пометить живой токен» не
/// является ни тем, ни другим, и дописанный туда метод пришлось бы объяснять в обоих местах.
///
/// Код проверяет модуль учётных записей, отметку хранит модуль токенов и отдаёт её в личности
/// запроса. По ней личность отличает полноценную сессию от сессии настройки, а
/// <see cref="Authz.IStepUpFreshness"/> — свежий второй фактор от давнего перед опасными
/// действиями.
///
/// ⚠ <b>Отметка на ТОКЕНЕ, а не на человеке.</b> Своя таблица «когда
/// этот человек подтверждался последний раз» дала бы то же поле с той же меткой времени —
/// и другой смысл: переподтверждение в одной вкладке открывало бы опасное во всех сессиях
/// человека и на другом его устройстве, а украденная живая сессия начинала бы работать
/// оттого, что законный владелец ввёл код у себя.
/// </remarks>
public interface IStepUpMarker
{
    /// <summary>
    /// Записать, что личность за этим токеном только что подтвердили.
    /// </summary>
    /// <param name="tokenId">Строка выдачи — <see cref="TokenIdentity.TokenId"/>.</param>
    /// <param name="at">Когда подтвердили.</param>
    /// <param name="cancellationToken">Отмена.</param>
    /// <returns>
    /// <c>true</c> — отметка легла на живой токен. <c>false</c> — токена нет или он отозван.
    /// <para>
    /// ⚠ Отказ возвращается значением, а не исключением, намеренно: единственный способ
    /// сюда попасть — токен, отозванный между распознаванием и проверкой кода, и это не
    /// сбой, а гонка, у которой правильный исход один — «подтверждение не состоялось».
    /// </para>
    /// </returns>
    Task<bool> MarkAsync(Guid tokenId, DateTimeOffset at, CancellationToken cancellationToken = default);
}
