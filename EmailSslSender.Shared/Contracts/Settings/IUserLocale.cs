namespace EmailSslSender.Shared.Contracts.Settings;

/// <summary>
/// На каком языке писать вот этому человеку.
/// </summary>
/// <remarks>
/// ⚠ ⚠ <b>Узкий контракт вместо широкого, и это выбор, а не полумера.</b> Вопрос «какая локаль у
/// вот этого человека» нельзя задать через <see cref="ISettingsReader"/>: тот отвечает про
/// <b>обратившегося</b>, а письмо уходит не тому, кто в запросе, — приглашение, сброс,
/// блокировка, код при входе. Ни в одном из четырёх случаев получатель не совпадает с
/// действующим лицом.
///
/// Рассматривались два других выхода, оба хуже:
///
/// <list type="number">
/// <item><b>Параметр субъекта у <see cref="ISettingsReader"/></b> — <c>GetForUserAsync(key,
/// userId)</c>. Это разрешение любому модулю читать <b>любую</b> личную настройку любого
/// человека. Сегодня личных настроек шесть и все безобидны; завтра кто-нибудь объявит личной
/// настройку, которая безобидной не будет, — и право читать её у всех уже роздано.</item>
/// <item><b>Своя колонка локали у <c>Identity</c></b> — седьмая настройка интерфейса в обход
/// таблицы настроек. Два места, где живёт язык человека, разойдутся: он поменяет его на экране,
/// а письма продолжат приходить на прежнем.</item>
/// </list>
///
/// ⚠ <b>Контракт уже был и был снят за отсутствием потребителей.</b> Теперь потребитель есть
/// (этап 17.6), и мера правила 19 сходится: удали контракт — сломаются оба, и <c>Identity</c>,
/// которому нечем спросить, и <c>Settings</c>, которому некому отвечать. Тот же счёт, что у
/// <see cref="Mail.IMailQueue"/>.
///
/// ⚠ <b>Отвечает ВСЕГДА</b>, в том числе про человека, которого нет: язык — не право, и
/// «не знаю» здесь означало бы письмо, которое не на чем написать. Не знаем — пишем на языке
/// установки.
/// </remarks>
public interface IUserLocale
{
    /// <summary>Язык человека: <c>uk</c>, <c>ru</c> или <c>en</c>.</summary>
    Task<string> ForAsync(Guid userId, CancellationToken cancellationToken = default);
}
