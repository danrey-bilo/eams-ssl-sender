namespace EmailSslSender.Shared.Contracts.Settings;

/// <summary>
/// Внешний адрес установки.
/// </summary>
/// <remarks>
/// ⚠ ⚠ <b>Два члена, потому что у двух потребителей разные требования — и разница несущая.</b>
///
/// <list type="bullet">
/// <item><b>Ссылка внутри письма строится ТОЛЬКО из <see cref="ConfiguredAsync"/></b>, то есть из
/// заданного руками значения. Заголовок <c>Host</c> подделывается: письмо со ссылкой сброса,
/// собранной по нему, уехало бы вместе с токеном на сервер атакующего, и человек, перешедший по
/// ней, отдал бы ему свою учётную запись. Настройка пуста — письмо не ставится вовсе, и об этом
/// говорится строкой в логе.</item>
/// <item><b>Адрес скачивания может опираться на заголовки прокси</b> (<see cref="ResolveAsync"/>):
/// ошибка там стоит нерабочей кнопки, а не угнанной учётной записи.</item>
/// </list>
///
/// ⚠ <b>Почте этот контракт НЕ НУЖЕН вовсе.</b> Ссылку внутрь письма подставляет вызывающий:
/// иначе почта обязана знать, что <c>/activate</c> и <c>/password-reset</c> — адреса
/// веб-интерфейса, то есть знать про чужой клиент.
/// </remarks>
public interface IPublicOrigin
{
    /// <summary>
    /// Адрес, заданный настройкой. <c>null</c> — не задан.
    /// </summary>
    /// <remarks>
    /// ⚠ Единственный источник, годный для ссылок в письмах.
    /// </remarks>
    Task<string?> ConfiguredAsync(CancellationToken cancellationToken = default);

    /// <summary>
    /// Адрес для показа: заданный, иначе — выведенный из текущего запроса.
    /// </summary>
    /// <remarks>
    /// ⚠ Для ссылок в письмах <b>не годится</b>: значение может быть выведено из подделываемых
    /// заголовков.
    /// </remarks>
    Task<string?> ResolveAsync(CancellationToken cancellationToken = default);
}
