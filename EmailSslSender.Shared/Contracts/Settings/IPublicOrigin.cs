namespace EmailSslSender.Shared.Contracts.Settings;

/// <summary>
/// Внешний адрес установки.
/// </summary>
/// <remarks>
/// ⚠ ⚠ <b>Ссылка внутри письма строится ТОЛЬКО из заданного руками значения</b>, а не из запроса.
/// Заголовок <c>Host</c> подделывается: письмо со ссылкой сброса, собранной по нему, уехало бы
/// вместе с токеном на сервер атакующего, и человек, перешедший по ней, отдал бы ему свою учётную
/// запись. Настройка пуста — письмо не ставится вовсе, и об этом говорится строкой в логе.
///
/// ⚠ <b>Почте этот контракт НЕ НУЖЕН вовсе.</b> Ссылку внутрь письма подставляет вызывающий:
/// иначе почта обязана знать, что <c>/activate</c> и <c>/password-reset</c> — адреса
/// веб-интерфейса, то есть знать про чужой клиент.
/// </remarks>
public interface IPublicOrigin
{
    /// <summary>
    /// Адрес, заданный настройкой. <c>null</c> — не задан.
    /// </summary>
    /// <remarks>
    /// ⚠ Единственный источник, годный для ссылок в письмах.
    /// </remarks>
    Task<string?> ConfiguredAsync(CancellationToken cancellationToken = default);
}
