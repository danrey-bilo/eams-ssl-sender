using EmailSslSender.Shared.Contracts.Tokens;

namespace EmailSslSender.Modules.Tokens.Domain;

/// <summary>
/// Одна выданная возможность предъявляться системе.
/// </summary>
/// <remarks>
/// Сегодня вид один — сессия человека (<see cref="Kind"/>); в EAMS та же таблица держала и
/// токены клиентов, и ключи интеграции.
///
/// ⚠ <b>Одна таблица на все виды — это и есть весь смысл модуля.</b> Место ротации, место
/// обнаружения кражи и список «где я вошёл» обязаны быть одними. Разведи их по таблицам — и
/// обнаружение повторного предъявления окажется написанным дважды, а разойдутся эти две
/// реализации молча.
///
/// Сами секреты живут отдельно (<see cref="AuthTokenSecret"/>) и меняются по многу раз за
/// жизнь токена; строка здесь при этом одна.
/// </remarks>
internal sealed class AuthToken
{
    public Guid Id { get; set; }

    /// <summary>
    /// Чей.
    /// </summary>
    /// <remarks>
    /// ⚠ <b>Без внешнего ключа на <c>users</c> — намеренно, и это правило 1.</b> Таблица
    /// людей принадлежит соседнему модулю; внешний ключ на неё означал бы, что схема этого
    /// модуля не разворачивается без него. Каскадное удаление, которое ключ давал прежде,
    /// заменено явным вызовом <c>ITokenRevoker</c> при удалении человека.
    /// </remarks>
    public Guid UserId { get; set; }

    /// <summary>Вид: <see cref="TokenKinds"/>.</summary>
    public string Kind { get; set; } = TokenKinds.Session;

    /// <summary>
    /// Как токен называется в списке.
    /// </summary>
    /// <remarks>
    /// Для сессии — агент браузера или клиента. Поле общее на все виды, потому что вопрос
    /// один: «а это что такое».
    /// </remarks>
    public string? Name { get; set; }

    /// <summary>Откуда предъявляли в последний раз.</summary>
    public System.Net.IPAddress? Address { get; set; }



    /// <summary>
    /// Когда личность за этим токеном подтверждали последний раз. <c>null</c> — не подтверждали.
    /// </summary>
    /// <remarks>
    /// ⚠ <b>Колонка здесь, а не в таблице людей</b> (решение
    /// <c>docs/decisions/0023-хранилища-ответы-до-первой-строки.md</c> §3): отметка привязана
    /// к тому, чем вошли. Иначе переподтверждение в одной вкладке открыло бы секреты во всех
    /// сессиях человека, а украденная живая сессия начала бы работать оттого, что законный
    /// владелец ввёл код у себя.
    ///
    /// ⚠ <b>Срока годности у отметки нет.</b> Действия после входа свежего кода не требуют
    /// (решение владельца, 2026-10-20); отметка лишь отличает полноценную сессию от сессии
    /// настройки.
    /// </remarks>
    public DateTimeOffset? StepUpAt { get; set; }

    public DateTimeOffset CreatedAt { get; set; }

    /// <summary>Когда токеном пользовались в последний раз.</summary>
    /// <remarks>
    /// Двигается обновлением, а не каждым запросом: запись в базу на каждое обращение
    /// превратила бы чтение в запись, а точность до минут здесь никому не нужна.
    /// </remarks>
    public DateTimeOffset LastSeenAt { get; set; }

    /// <summary>
    /// Когда кончится, сколько бы им ни пользовались.
    /// </summary>
    /// <remarks>
    /// ⚠ <b>Абсолютный срок, а не только простой.</b> Сессия, продлеваемая обновлением
    /// токена, иначе живёт вечно — и украденный refresh-токен вместе с ней. Оба срока
    /// нужны: простой закрывает забытый ноутбук, абсолютный закрывает кражу.
    /// </remarks>
    public DateTimeOffset ExpiresAt { get; set; }

    /// <summary>Когда отозван. <c>null</c> — жив.</summary>
    public DateTimeOffset? RevokedAt { get; set; }

    /// <summary>
    /// Почему отозван.
    /// </summary>
    /// <remarks>
    /// Это единственное, что экран входа может показать человеку вместо голого «войдите
    /// заново»: вышли сами, отозвал администратор, обнаружена кража токена, учётная запись
    /// отключена. Разница между ними — разница между «ладно» и «звоните в безопасность».
    /// </remarks>
    public string? RevokedReason { get; set; }
}
