using EmailSslSender.Shared.Contracts.Audit;

namespace EmailSslSender.Modules.Tokens.Contracts;

/// <summary>
/// События, которые пишет модуль токенов.
/// </summary>
/// <remarks>
/// ⚠ <b>Три события приехали из модуля личностей НЕ переименовываясь</b> (этап 10.5.4):
/// <c>auth.session_revoked</c>, <c>auth.token_reuse</c>, <c>auth.cleanup</c>. Имя события
/// лежит в уже написанных строках append-only журнала и в сохранённых фильтрах выдачи;
/// переименование сделало бы прошлые строки ненаходимыми по тому же фильтру — то есть
/// разбор происшествия за прошлый месяц дал бы пустой список.
///
/// ⚠ <b>Приставка <c>auth.</c> сохраняется, хотя владелец сменился.</b> Правило 2 говорит,
/// что приставка называет владельца, — и здесь она с ним расходится. Цена переименования
/// (см. выше) выше цены расхождения, и расхождение названо, а не спрятано.
/// </remarks>
public static class TokenActions
{
    /// <summary>Токен закрыт: вышли сами, отозвали, кончился срок.</summary>
    public static readonly AuditAction Revoked = new("auth.session_revoked", "Сессия закрыта");

    /// <summary>
    /// Предъявлен уже потраченный токен обновления.
    /// </summary>
    /// <remarks>
    /// ⚠ Самое тревожное событие модуля. Означает, что токен есть у двоих, и кто из них
    /// вор — неизвестно. Пишется отказом, чтобы попадать в тот же фильтр, что и остальные
    /// отказы безопасности.
    /// </remarks>
    public static readonly AuditAction Reuse = new("auth.token_reuse", "Повторное использование токена");

    /// <summary>Уборка мёртвых токенов и секретов.</summary>
    /// <remarks>
    /// Пишется системой и только когда что-то действительно убрано. Нужна затем, чтобы
    /// вопрос «куда делись сессии за прошлый год» имел ответ, а неверно выставленный срок
    /// хранения было видно по счётчикам, а не по опустевшей таблице.
    /// </remarks>
    public static readonly AuditAction Cleaned = new("auth.cleanup", "Уборка сессий");
}
