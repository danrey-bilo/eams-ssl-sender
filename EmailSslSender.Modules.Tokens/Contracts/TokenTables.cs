namespace EmailSslSender.Modules.Tokens.Contracts;

/// <summary>
/// Имена таблиц модуля.
/// </summary>
/// <remarks>
/// <b>Публично — потому что на них ссылаются миграции</b>, а живут они у хоста: модуль не
/// знает провайдера базы, а миграция без него не пишется. Строка, повторённая в миграции
/// руками, разошлась бы с конфигурацией молча — и обнаружилось бы это на установке, где
/// таблицу не нашли.
///
/// ⚠ <b>Имена не меняются.</b> Переименование таблицы — это миграция с переименованием
/// каждого ограничения и каждого индекса по отдельности (иначе в базе остаются старые имена,
/// а снимок модели думает иначе); один раз этот модуль уже через это прошёл на этапе 10.5.3.
/// </remarks>
public static class TokenTables
{
    /// <summary>Выданные токены. Прежде — <c>sessions</c> у модуля личностей.</summary>
    public const string Tokens = "auth_tokens";

    /// <summary>Секреты выданных токенов. Прежде — <c>session_tokens</c>.</summary>
    public const string Secrets = "auth_token_secrets";
}
