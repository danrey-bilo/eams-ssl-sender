#!/bin/sh
# Вернуть доступ к учётной записи, когда войти больше некому: потерян телефон с
# аутентификатором, забыт пароль или учётная запись заперта после неудачных входов.
#
#   ./scripts/reset-access.sh admin@example.com
#
# Одной транзакцией: новый пароль (спрашивается скрытым вводом дважды — в истории оболочки и
# в `ps` его не будет), второй фактор снят, блокировка снята, все сессии закрыты, ссылки и коды
# погашены. Следующий вход потребует заново подключить приложение-аутентификатор.
# Отключённую учётную запись команда НЕ включает и говорит об этом.
#
# Внутри — `docker compose run --rm api reset-access --email <адрес>`; запускать там же, где
# лежит docker-compose.yml (скрипт сам переходит в корень установки).
set -eu

usage() {
    echo "Использование: $0 <адрес учётной записи>"
    echo "Пример:        $0 admin@example.com"
}

case "${1:-}" in
    -h|--help)
        usage
        exit 0
        ;;
    ""|-*)
        usage >&2
        exit 2
        ;;
esac

if [ "$#" -ne 1 ]; then
    usage >&2
    exit 2
fi

cd "$(dirname "$0")/.."

exec docker compose run --rm api reset-access --email "$1"
