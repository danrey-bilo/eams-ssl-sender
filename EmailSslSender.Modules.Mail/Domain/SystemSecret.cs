namespace EmailSslSender.Modules.Mail.Domain;

/// <summary>
/// Секрет установки, запечатанный конвертом.
/// </summary>
/// <remarks>
/// ⚠ ⚠ <b>Две колонки, а не одна, и вторая — не украшение.</b> Соблазн запечатать пароль SMTP
/// прямо мастер-ключом стоит пять строк; цена — смена мастер-ключа перестаёт быть
/// перекладыванием обёрток и становится <b>перешифровкой каждого секрета</b>, а
/// <c>IRewrapTarget</c> теряет смысл. Поэтому у каждого секрета свой ключ данных, обёрнутый
/// мастер-ключом: ротация переворачивает обёртки, не трогая содержимое.
///
/// ⚠ <b>Набор имён закрыт В КОДЕ</b> (<c>SystemSecretNames</c>), а не в схеме. В базе это
/// обычный <c>text</c>; ограничение живёт там, где его читают, — иначе следующий модуль
/// положит сюда что попало, и таблица станет свалкой.
///
/// ⚠ <b><c>bytea</c>, а не <c>text</c> через base64.</b> Лишний слой, в котором однажды
/// потеряется байт, плюс вид, приглашающий скопировать значение.
/// </remarks>
internal sealed class SystemSecret
{
    /// <summary>Имя из закрытого набора.</summary>
    public required string Key { get; set; }

    /// <summary>Запечатанное значение.</summary>
    public required byte[] Sealed { get; set; }

    /// <summary>Ключ данных, обёрнутый мастер-ключом. Его переворачивает ротация.</summary>
    public required byte[] DataKey { get; set; }

    /// <summary>
    /// Когда правили в последний раз.
    /// </summary>
    /// <remarks>
    /// ⚠ Проставляется <b>командой upsert</b>, а не трекером: <c>onupdate</c> у EF нет вовсе,
    /// и колонка показывала бы дату первой записи, молча про все последующие.
    /// </remarks>
    public DateTimeOffset UpdatedAt { get; set; }

    /// <summary>Кто правил. Без внешнего ключа: <c>users</c> — чужая таблица (правило 1).</summary>
    public Guid? UpdatedBy { get; set; }
}
