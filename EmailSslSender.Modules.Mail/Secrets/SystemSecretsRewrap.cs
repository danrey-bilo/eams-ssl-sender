using EmailSslSender.Modules.Mail.Domain;
using EmailSslSender.Shared.Crypto;
using EmailSslSender.Shared.Data;
using Microsoft.EntityFrameworkCore;

namespace EmailSslSender.Modules.Mail.Secrets;

/// <summary>
/// Перекладывает обёртки ключей системных секретов под действующую версию мастер-ключа.
/// </summary>
/// <remarks>
/// ⚠ ⚠ <b>Написан в том же подэтапе, что и запечатывание, а не позже.</b> Цель ротации,
/// добавленная через месяц, означает месяц, в течение которого мастер-ключ нельзя вывести из
/// обращения, — и никто об этом не знает: команда <c>rewrap-keys</c> отработает и отчитается
/// об успехе, не тронув пароль SMTP.
///
/// ⚠ <b>Трогается только обёртка.</b> Сам секрет не расшифровывается вовсе: мастер-ключ шифрует
/// ключ данных, а не данные. Открытый пароль SMTP в память при перекладывании не попадает ни на
/// мгновение.
///
/// ⚠ <b>Отбирать «нуждающиеся» запросом нельзя</b> — версия лежит внутри байтов обёртки, а не
/// колонкой. Проход идёт по всем строкам и решает по каждой отдельно; курсор — имя секрета: оно
/// неизменно, уникально и упорядочено.
///
/// ⚠ <b>Строк здесь единицы, и порционность всё равно нужна</b> — не ради размера, а ради
/// одинаковости: реализация, устроенная иначе «потому что строк мало», расходится с остальными
/// целями ровно тогда, когда в таблицу положат что-нибудь ещё.
/// </remarks>
internal sealed class SystemSecretsRewrap(SenderDbContext db, ISecretEnvelope envelope) : IRewrapTarget
{
    public string Name => "system_secrets";

    public Task<RewrapBatch> RewrapAsync(
        int batch, string? after = null, CancellationToken cancellationToken = default) =>
        db.InTransactionAsync(
            async (token) =>
            {
                var от = after ?? string.Empty;

                // Без отслеживания: писать будем условным обновлением, а не через трекер.
                var строки = await db.Set<SystemSecret>()
                    // ⚠ `string.Compare` БЕЗ `StringComparison`: перегрузку с ним EF в SQL
                    // не переводит и роняет запрос в рантайме. Сравнение идёт по сортировке
                    // базы — той же, по которой ниже идёт `OrderBy`, так что курсор не
                    // перескочит строку и не покажет её дважды.
                    .Where(с => string.Compare(с.Key, от) > 0)
                    .OrderBy(с => с.Key)
                    .Take(Math.Max(1, batch))
                    .AsNoTracking()
                    .ToListAsync(token);

                if (строки.Count == 0)
                {
                    return new RewrapBatch(0, 0, null);
                }

                var переложено = 0;

                foreach (var строка in строки)
                {
                    var было = строка.DataKey;
                    var ключ = new WrappedDataKey(было);

                    // мутация 2026-08-29: обезвредил условие → покраснели два факта
                    // SecretsTests (правило 9).
                    //
                    // ⚠ Уже под действующей версией — не трогаем. Без этой проверки повторный
                    // запуск переписывал бы столбец с ключом у всех подряд, а перезапись
                    // столбца с ключом — единственное место, где сбой стоит секрета.
                    if (!envelope.NeedsRewrap(ключ))
                    {
                        continue;
                    }

                    var стало = envelope.Rewrap(ключ).Bytes;

                    // мутация 2026-08-29: убрал условие `с.DataKey == было` → покраснел
                    // SecretsTests.Строка_изменившаяся_между_чтением_и_записью_НЕ_затирается
                    // (правило 9). ⚠ Первая редакция этого теста мутацию НЕ убивала: сценарий
                    // «перезадали до ротации» до условия не доходит вовсе. Понадобилось
                    // вклинивание перехватчиком между чтением порции и записью.
                    //
                    // ⚠ УСЛОВНЫМ обновлением, а не присваиванием. Между чтением порции и записью
                    // администратор мог задать пароль заново: `PutAsync` заменяет и ключ, и
                    // запечатанное. Присвоив своё, мы положили бы обёртку от СТАРОГО ключа
                    // поверх нового — а запечатанное рядом уже новое, и открыть его стало бы
                    // нечем. Это не «строка потерялась»: это молча испорченный пароль SMTP,
                    // и обнаружится он тем, что письма перестали уходить.
                    //
                    // Не сошлось — пропускаем: значит пароль перезадали, и его обёртка и так
                    // под действующей версией.
                    var затронуто = await db.Set<SystemSecret>()
                        .Where(с => с.Key == строка.Key && с.DataKey == было)
                        .ExecuteUpdateAsync(set => set.SetProperty(с => с.DataKey, стало), token);

                    if (затронуто == 1)
                    {
                        переложено++;
                    }
                }

                // Прочитали меньше, чем просили — значит дошли до конца.
                var дальше = строки.Count < Math.Max(1, batch) ? null : строки[^1].Key;

                return new RewrapBatch(строки.Count, переложено, дальше);
            },
            cancellationToken);
}
