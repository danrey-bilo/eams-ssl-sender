namespace EmailSslSender.Modules.Mail.Sending;

/// <summary>
/// Сигнал насосу: в очередь легло письмо, спать больше не надо.
/// </summary>
/// <remarks>
/// ⚠ ⚠ ⚠ <b>Заведён вместе с разрежением хода и без него не имеет смысла (этап 60.2).</b> Насос
/// ходил каждые пятнадцать секунд <b>всегда</b> — то есть 11 520 холостых пар запросов в сутки
/// на установке, где почты нет вовсе. Разредить ход до минуты просто; цена простого решения —
/// письмо с кодом входа, которое ждут <b>прямо сейчас, у экрана</b>, уходит через минуту вместо
/// пятнадцати секунд. Это хуже, чем было, и ради экономии на пустых запросах такого не делают.
///
/// ⚠ ⚠ <b>Сигнал делает обратное: письмо уходит СРАЗУ, а не через пятнадцать секунд.</b> То
/// есть разрежение не ухудшает задержку, а улучшает её — и именно поэтому его можно вводить.
///
/// ⚠ <b>Сигнал внутрипроцессный, и это осознанно.</b> `LISTEN/NOTIFY` не заводится (решение
/// плана ревью): очередь захватывается атомарно (`FOR UPDATE SKIP LOCKED`), и письмо, положенное
/// в другом процессе, дождётся своего прохода по расписанию — с разрежением до минуты в худшем
/// случае. Кладёт письма тот же процесс, что и отвечает человеку у экрана (`api`), а его насос
/// проснётся немедленно.
///
/// ⚠ <b>Взведённый сигнал не теряется</b>, даже если насос сейчас занят проходом: он
/// запоминается, и следующий заход не спит. Иначе письмо, положенное ровно во время прохода,
/// ждало бы полного разрежённого интервала — то есть худший случай выпал бы на самый занятый
/// момент.
/// </remarks>
internal sealed class MailWakeup
{
    private readonly SemaphoreSlim _сигнал = new(0, 1);

    /// <summary>В очередь легло письмо.</summary>
    /// <remarks>
    /// ⚠ Повторный сигнал при уже взведённом ничего не добавляет и не бросает: насос всё равно
    /// заберёт порцию целиком, а не по письму.
    /// </remarks>
    public void Signal()
    {
        if (_сигнал.CurrentCount == 0)
        {
            try
            {
                _сигнал.Release();
            }
            catch (SemaphoreFullException)
            {
                // Гонка двух одновременных вызовов: сигнал уже взведён, и это всё, что нужно.
            }
        }
    }

    /// <summary>
    /// Подождать письма или срока. <c>true</c> — разбудили письмом.
    /// </summary>
    /// <remarks>
    /// ⚠ Отмена — это останов процесса, а не «письма не было»: она пробрасывается наружу, чтобы
    /// служба вышла из цикла, а не сделала ещё один проход по дороге к остановке.
    /// </remarks>
    public async Task<bool> WaitAsync(TimeSpan сколько, CancellationToken cancellationToken) =>
        await _сигнал.WaitAsync(сколько, cancellationToken);
}
