using EmailSslSender.Shared.Errors;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Logging;

namespace EmailSslSender.Modules.Mail.Sending;

/// <summary>
/// Насос очереди писем: по сигналу и по сроку, срок разрежается на пустой очереди.
/// </summary>
/// <remarks>
/// ⚠ ⚠ ⚠ <b>С этапа 60.2 насос ходит НЕ по расписанию, а по сигналу и по сроку.</b> Прежде он
/// просыпался каждые пятнадцать секунд <b>всегда</b> — 11 520 холостых пар запросов в сутки на
/// установке, где почты нет вовсе. Теперь: письмо, легшее в очередь, будит его <b>немедленно</b>
/// (<see cref="MailWakeup"/>), а без писем срок растёт с пятнадцати секунд до минуты.
///
/// ⚠ ⚠ <b>Разрежение без сигнала было бы ухудшением, а не улучшением.</b> Письмо с кодом входа
/// ждут прямо сейчас, у экрана; минута ожидания читается как «не работает». Поэтому сигнал —
/// не украшение к разрежению, а условие, при котором его вообще можно вводить: с ним задержка
/// стала <b>меньше</b> прежней (ноль вместо пятнадцати секунд), а не больше.
///
/// ⚠ <b>Разрежение считает ВЗЯТЫЕ строки, а не ушедшие.</b> Порция, которая вся отказала,
/// означает «сервер не отвечает, но работа есть»: разредить ход тут значило бы добавить минуту
/// к письму, которое вот-вот пройдёт.
///
/// ⚠ <b>Поднимается и в <c>api</c>, и в <c>worker</c>.</b> Это не дублирование: захват порции
/// атомарен (<c>FOR UPDATE SKIP LOCKED</c>), и два процесса делят очередь, а не повторяют друг
/// друга. Зато письмо уходит и тогда, когда воркер не поднят.
///
/// ⚠ <b>Ошибка прогона НЕ роняет службу.</b> Недоступная база или сорванная сеть — это
/// пропущенный проход, а не повод остановить отправку до перезапуска процесса.
/// </remarks>
internal sealed class MailDeliveryService(
    IServiceScopeFactory scopes,
    MailWakeup wakeup,
    ILogger<MailDeliveryService> log) : BackgroundService
{
    /// <summary>Обычный срок: столько ждали всегда, и столько ждём при живой очереди.</summary>
    private static readonly TimeSpan Обычный = TimeSpan.FromSeconds(15);

    /// <summary>
    /// Потолок разрежения.
    /// </summary>
    /// <remarks>
    /// ⚠ Минута, а не больше: сигнал внутрипроцессный, и письмо, положенное <b>другим</b>
    /// процессом, дождётся только срока. Минута — предел, за которым это перестаёт быть
    /// незаметным.
    /// </remarks>
    private static readonly TimeSpan Потолок = TimeSpan.FromMinutes(1);

    /// <summary>Сколько пустых проходов терпим, прежде чем удваивать срок.</summary>
    private const int ПустыхДоРазрежения = 4;

    /// <summary>
    /// Короткий догляд после пустого прохода, разбуженного сигналом.
    /// </summary>
    /// <remarks>
    /// ⚠ ⚠ Сигнал даётся ДО фиксации строки (разбор у <c>MailQueue.EnqueueAsync</c>), и насос
    /// нередко приходит раньше неё: захват в READ COMMITTED незафиксированной строки не видит
    /// (ревью 2026-09-15, mail-1). Прежде такой проход считался обычным пустым — сигнал
    /// израсходован, счётчик разрежения растёт, и код входа ждал полный срок, до минуты. Две
    /// секунды покрывают вставку и фиксацию запроса с большим запасом.
    /// </remarks>
    internal static readonly TimeSpan Догляд = TimeSpan.FromSeconds(2);

    protected override async Task ExecuteAsync(CancellationToken stoppingToken)
    {
        var пустых = 0;
        var поСигналу = false;

        while (!stoppingToken.IsCancellationRequested)
        {
            var после = await ПройтиAsync(пустых, stoppingToken);
            (пустых, var срок) = Следующий(пустых, после, поСигналу);

            var ожидание = await ЖдатьAsync(срок, stoppingToken);

            if (ожидание is null)
            {
                return;
            }

            поСигналу = ожидание.Value;
        }
    }

    /// <summary>
    /// Что делать после прохода: новый счётчик пустых и сколько спать.
    /// </summary>
    /// <remarks>
    /// ⚠ ⚠ <b>Пустой проход ПО СИГНАЛУ — не пустой проход</b> (ревью 2026-09-15, mail-1). Письмо
    /// положено, но ещё не зафиксировано: разрежать ход по нему и тратить на это сигнал нельзя.
    /// Счётчик остаётся прежним, а следующий захват — через <see cref="Догляд"/>. Догляд сам
    /// сигналом не разбужен, и если и он пуст, проход считается обычным: ложное пробуждение
    /// (отправка откатилась) стоит ровно одного лишнего короткого прохода.
    ///
    /// <c>internal static</c> по той же причине, что <see cref="Срок"/>: иначе проверять это
    /// пришлось бы минутой реального времени.
    ///
    /// мутация 2026-09-15: вернул `(после, Срок(после))` без ветки сигнала → покраснел
    /// PumpTests.Пустой_проход_по_сигналу_не_разрежает_ход_и_приходит_снова_скоро.
    /// </remarks>
    internal static (int Пустых, TimeSpan Срок) Следующий(int было, int после, bool поСигналу) =>
        поСигналу && после > было
            ? (было, Догляд)
            : (после, Срок(после));

    /// <summary>
    /// Сколько спать после N пустых проходов подряд.
    /// </summary>
    /// <remarks>
    /// ⚠ ⚠ <c>internal static</c>, а не приватный: разрежение — арифметика, которую иначе
    /// проверять пришлось бы прогоном на минуту реального времени. Ровно тот же довод, что у
    /// <c>SessionTab.Решить</c> в клиенте.
    ///
    /// ⚠ Удвоение начинается только после четырёх пустых подряд: на установке с редкой, но
    /// живой почтой первый же пустой проход не должен удлинять ожидание вдвое.
    /// </remarks>
    internal static TimeSpan Срок(int пустыхПодряд)
    {
        if (пустыхПодряд < ПустыхДоРазрежения)
        {
            return Обычный;
        }

        var множитель = 1 << Math.Min(пустыхПодряд - ПустыхДоРазрежения + 1, 8);
        var срок = Обычный * множитель;

        return срок < Потолок ? срок : Потолок;
    }

    /// <summary>Один проход. Возвращает новый счётчик пустых подряд.</summary>
    private async Task<int> ПройтиAsync(int пустых, CancellationToken cancellationToken)
    {
        try
        {
            await using var scope = scopes.CreateAsyncScope();

            var итог = await scope.ServiceProvider
                .GetRequiredService<MailDelivery>()
                .RunAsync(cancellationToken);

            // ⚠ Считаются ВЗЯТЫЕ, а не ушедшие: порция, которая вся отказала, — это «сервер не
            // отвечает, но работа есть», и разреживать ход тут нельзя.
            return итог.Taken == 0 ? пустых + 1 : 0;
        }
        catch (OperationCanceledException) when (cancellationToken.IsCancellationRequested)
        {
            // Останов процесса.
            return пустых;
        }
        catch (Exception ошибка)
        {
            // ⚠ Описанием, а не исключением объектом: строка подключения Npgsql содержит
            // пароль целиком (правило 14).
            log.LogError("mail_delivery_failed {Error}", SafeError.Describe(ошибка));

            // ⚠ Отказ прохода — не пустая очередь: недоступная база не повод спать дольше.
            return 0;
        }
    }

    /// <summary>
    /// Подождать письма или срока: <c>true</c> — разбудил сигнал, <c>false</c> — срок,
    /// <c>null</c> — процесс останавливают.
    /// </summary>
    private async Task<bool?> ЖдатьAsync(TimeSpan сколько, CancellationToken stoppingToken)
    {
        try
        {
            return await wakeup.WaitAsync(сколько, stoppingToken);
        }
        catch (OperationCanceledException)
        {
            return null;
        }
    }
}
