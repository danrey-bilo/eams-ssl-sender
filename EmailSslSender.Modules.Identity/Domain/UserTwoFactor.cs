namespace EmailSslSender.Modules.Identity.Domain;

/// <summary>
/// Второй фактор человека: запечатанный секрет и память о принятом коде.
/// </summary>
/// <remarks>
/// <b>Отдельная таблица, а не колонки в <c>users</c>.</b> Второй фактор есть не у всех, и
/// хранить пять пустых колонок у каждого значило бы платить местом за меньшинство. Важнее
/// другое: удаление строки — это и есть отключение фактора, и оно не требует помнить, какие
/// именно поля обнулять.
///
/// ⚠ <b>Секрет здесь запечатан конвертом (этап 7.5) и в открытом виде не хранится.</b> Это
/// первый по-настоящему обратимый секрет в системе: пароли и токены только хешируются, а
/// seed надо уметь развернуть — иначе нечем считать код. Привязка к месту
/// (<c>user:{id}:totp_seed</c>) означает, что перенесённая в чужую строку запись не
/// откроется.
/// </remarks>
internal sealed class UserTwoFactor
{
    /// <summary>Чей. Он же первичный ключ: фактор у человека один.</summary>
    public Guid UserId { get; set; }

    /// <summary>Ключ данных этой строки, обёрнутый мастер-ключом.</summary>
    /// <remarks>
    /// Свой на каждого человека, а не один на систему: удаление строки уносит с собой ключ,
    /// то есть секрет становится нечитаемым даже из резервной копии базы.
    /// </remarks>
    public byte[] DataKey { get; set; } = [];

    /// <summary>Запечатанный seed.</summary>
    public byte[] Secret { get; set; } = [];

    /// <summary>Когда завели.</summary>
    public DateTimeOffset CreatedAt { get; set; }

    /// <summary>
    /// Когда подтвердили кодом. До этого фактор не действует.
    /// </summary>
    /// <remarks>
    /// ⚠ Два состояния, а не одно. Заведённый, но неподтверждённый секрет означает, что
    /// человек нажал «включить» и не довёл дело до конца — например, не смог отсканировать
    /// код. Считать такой фактор действующим значило бы запереть его снаружи собственной
    /// учётной записи.
    /// </remarks>
    public DateTimeOffset? ConfirmedAt { get; set; }

    /// <summary>
    /// Шаг последнего принятого кода.
    /// </summary>
    /// <remarks>
    /// ⚠ Защита от повторного использования. Код живёт тридцать секунд, и подсмотренного
    /// через плечо хватает на второй вход, если не помнить, что его уже принимали.
    /// Минус единица — «ещё ни одного».
    /// </remarks>
    public long LastStep { get; set; } = -1;
}
