namespace EmailSslSender.Modules.Identity.Domain;

/// <summary>
/// Учётная запись человека.
/// </summary>
/// <remarks>
/// Схема перенесена с Python-версии; колонки второго фактора и сессий появятся своими
/// этапами, а не заранее — таблица растёт вместе с тем, что её использует.
/// </remarks>
internal sealed class User
{
    /// <summary>Идентификатор. Ставит база, чтобы он был и у строк, заведённых SQL'ом.</summary>
    public Guid Id { get; set; }

    /// <summary>
    /// Адрес, он же логин.
    /// </summary>
    /// <remarks>
    /// Тип колонки — <c>citext</c>: <c>User@x.com</c> и <c>user@x.com</c> это один логин, и
    /// завести обоих нельзя, иначе непонятно, кто из них войдёт. Регистр при этом хранится
    /// как ввели — человек видит свой адрес таким, каким его написал.
    ///
    /// Проверки формата нет, только длина. Единственный надёжный способ убедиться, что
    /// адрес существует, — послать на него письмо, и он ровно так и работает: без активации
    /// по ссылке войти нельзя.
    /// </remarks>
    public string Email { get; set; } = string.Empty;

    /// <summary>Как показывать человека. Может отсутствовать.</summary>
    public string? DisplayName { get; set; }

    /// <summary>
    /// Хеш пароля.
    /// </summary>
    /// <remarks>
    /// <b>NOT NULL и без умолчания.</b> «Пароля нет» выражается заведомо непроверяемым
    /// значением, а не <c>NULL</c>: иначе рано или поздно появится ветка
    /// <c>if (hash is null)</c>, трактующая это как «проверять нечего».
    ///
    /// Наружу не отдаётся ни одной схемой.
    /// </remarks>
    public string PasswordHash { get; set; } = string.Empty;

    /// <summary>
    /// Может ли входить.
    /// </summary>
    /// <remarks>
    /// ⚠ Ролей и прав в этой установке нет: каждая активная учётная запись — администратор с
    /// полным доступом. Поэтому активность — единственный рубильник доступа, и проверяется
    /// она на КАЖДОМ запросе (<c>SessionIdentityResolver</c>), а не при входе.
    /// </remarks>
    public bool IsActive { get; set; } = true;

    /// <summary>Пора сменить пароль: выданный администратором или просроченный.</summary>
    public bool MustChangePassword { get; set; }

    /// <summary>Когда пароль сменили в последний раз.</summary>
    /// <remarks>
    /// ⚠ <b>Не двигается при перехешировании.</b> Пересчёт хеша новыми параметрами argon2 —
    /// не смена пароля. На Python-версии двигается, и при включённом сроке годности пароля
    /// это обнуляет срок всем, кто вошёл после обновления библиотеки.
    /// </remarks>
    public DateTimeOffset? PasswordChangedAt { get; set; }

    /// <summary>Сколько неудачных входов подряд. Обнуляется успешным входом.</summary>
    public int FailedLoginCount { get; set; }

    /// <summary>До какого момента вход заблокирован перебором.</summary>
    public DateTimeOffset? LockedUntil { get; set; }

    /// <summary>
    /// Когда человек активировал учётную запись.
    /// </summary>
    /// <remarks>
    /// <c>NULL</c> — ещё нет, и войти он не может: пароля у него не существует. Отметка, а
    /// не флаг: «когда» отвечает на вопросы разбора, на которые <c>bool</c> не отвечает.
    ///
    /// ⚠ Ставится и на пути «пароль задал администратор», хотя ссылку там никто не открывал.
    /// Пропуск даёт не ошибку, а враньё: первый администратор показывался бы «Приглашён» —
    /// столбец активации врал бы про единственную учётную запись, которая заведомо работает.
    /// </remarks>
    public DateTimeOffset? ActivatedAt { get; set; }

    /// <summary>Когда владелец впервые подтвердил второй фактор. Не даёт сбою SMTP открыть повторную настройку по паролю.</summary>
    public DateTimeOffset? TwoFactorConfiguredAt { get; set; }

    public DateTimeOffset CreatedAt { get; set; }

    public DateTimeOffset UpdatedAt { get; set; }

    /// <summary>
    /// Мягкое удаление.
    /// </summary>
    /// <remarks>
    /// Физического удаления нет: на пользователя ссылаются строки лога (по идентификатору) и
    /// история писем. Удалённый теряет доступ немедленно —
    /// уникальность адреса при этом освобождается, и того же человека можно завести заново.
    /// </remarks>
    public DateTimeOffset? DeletedAt { get; set; }
}
