namespace EmailSslSender.Modules.Identity.Passwords;

/// <summary>
/// Хеширование и проверка паролей.
/// </summary>
/// <remarks>
/// Живёт в общей библиотеке, а не в модуле личностей: хешировать надо и ключи API, и коды
/// восстановления, и приглашения — то есть потребителей заведомо больше одного. Правило 19
/// прямо называет <c>Shared/Crypto</c> допустимым местом.
///
/// <b>Наружу отдаётся строка PHC и ничего больше.</b> Соль внутри неё, параметры внутри
/// неё; отдельных колонок под них не бывает, и вызывающему нечего забыть сохранить.
/// </remarks>
internal interface IPasswordHasher
{
    /// <summary>
    /// Посчитать хеш нового пароля.
    /// </summary>
    /// <returns>Строка PHC для колонки. Соль каждый раз новая, поэтому один и тот же пароль даёт разные строки.</returns>
    Task<string> HashAsync(string password, CancellationToken cancellationToken = default);

    /// <summary>
    /// Тот ли это пароль.
    /// </summary>
    /// <remarks>
    /// <c>false</c> на любой сбой, включая испорченную строку в колонке: вызывающий обязан
    /// обработать отказ одинаково, а разница между «не тот пароль» и «мусор в базе» не
    /// должна просачиваться в ответ.
    /// </remarks>
    Task<bool> VerifyAsync(string? encoded, string password, CancellationToken cancellationToken = default);

    /// <summary>
    /// Пора ли пересчитать этот хеш нынешними параметрами.
    /// </summary>
    /// <remarks>
    /// Спрашивать имеет смысл только после успешной проверки: другого момента, когда
    /// открытый пароль есть на руках, не будет.
    /// </remarks>
    bool NeedsRehash(string? encoded);

    /// <summary>
    /// Потратить столько же времени, сколько потратила бы проверка.
    /// </summary>
    /// <remarks>
    /// ⚠ <b>Не «на всякий случай», а затем, что иначе форма входа становится оракулом.</b>
    /// Без этого вызова ответ на несуществующий адрес возвращается на десятки миллисекунд
    /// быстрее, чем на существующий с неверным паролем, — и правило «вход не различает эти
    /// два случая» держится только на тексте ошибки, а не на поведении. Замерить разницу
    /// снаружи может кто угодно.
    ///
    /// Вызывается там, где проверять нечего: пользователь не найден, пароля у него нет,
    /// учётная запись заблокирована до сверки пароля.
    /// </remarks>
    Task WasteVerificationTimeAsync(CancellationToken cancellationToken = default);
}
