namespace EmailSslSender.Modules.Identity.Storage;

/// <summary>
/// Пользователь для ЧТЕНИЯ: только то, что уходит наружу.
/// </summary>
/// <remarks>
/// ⚠ ⚠ <b>Заведён затем, чтобы `password_hash` не покидал базу без надобности</b> (вскрытие
/// 27.7). Прежде чтение списка людей и чтение о себе брали сущность целиком — и argon2-хеш
/// каждого перечисленного уезжал по сети и ложился в память приложения, не будучи нужен ни
/// одному полю ответа.
///
/// ⚠ <b>Довод — правило 14, а не скорость, и это установлено замером</b>
/// (<c>docs/records/2026-09-02-чтение-людей-замер.md</c>): 97 байт на <c>/api/me</c> и 19.4 КБ
/// на предельной странице в двести человек — доли миллисекунды. Как оптимизация правка не
/// стоила бы того. Хеш пароля — материал для офлайнового подбора, и место ему не в выдаче
/// списка администраторов.
///
/// ⚠ <b>Почему отдельная запись, а не проекция в саму `User`.</b> EF умеет
/// <c>Select(u =&gt; new User { … })</c>, и это короче на десять строк — но даёт сущность,
/// заполненную наполовину. Следующий, кто её получит, увидит знакомый тип и вправе будет
/// ждать от него всех полей; пустой <c>PasswordHash</c> при этом выглядит как «пароля нет», а
/// не как «не читали». Отдельный тип отвечает на этот вопрос своим именем.
///
/// ⚠ <b>Пути ЗАПИСИ этим не затронуты.</b> Смене имени и пароля нужна отслеживаемая сущность
/// целиком — там по-прежнему <c>FindAsync</c>, и подменять его чтением нельзя.
/// </remarks>
/// <param name="Id">Идентификатор.</param>
/// <param name="Email">Адрес — он же логин.</param>
/// <param name="DisplayName">Имя для показа.</param>
/// <param name="IsActive">Не отключён.</param>
/// <param name="MustChangePassword">Обязан сменить пароль при следующем входе.</param>
/// <param name="ActivatedAt">Когда принял приглашение.</param>
/// <param name="LockedUntil">До какого времени вход заперт неудачными попытками.</param>
/// <param name="CreatedAt">Когда заведён.</param>
/// <param name="UpdatedAt">Когда последний раз менялся.</param>
internal sealed record UserRow(
    Guid Id,
    string Email,
    string? DisplayName,
    bool IsActive,
    bool MustChangePassword,
    DateTimeOffset? ActivatedAt,
    DateTimeOffset? LockedUntil,
    DateTimeOffset CreatedAt,
    DateTimeOffset UpdatedAt);
