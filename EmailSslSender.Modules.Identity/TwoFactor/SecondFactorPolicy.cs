using EmailSslSender.Modules.Identity.Domain;
using EmailSslSender.Modules.Identity.Settings;
using EmailSslSender.Shared.Contracts.Mail;
using EmailSslSender.Shared.Contracts.Settings;

namespace EmailSslSender.Modules.Identity.TwoFactor;

/// <summary>
/// Каким быть второму фактору у этого человека.
/// </summary>
/// <remarks>
/// ⚠ ⚠ <b>Способ не опускается ниже того, что у человека фактически есть — но выше
/// собственного выбора не поднимается.</b> Завёл аутентификатор и способ себе не выбирал —
/// фактор остаётся <c>totp</c>, что бы ни стояло в настройке установки. Это <b>регрессия
/// эталона</b>, а не улучшение по вкусу: там первая редакция читала только «выбор человека или
/// умолчание системы», и у человека с заведённым аутентификатором фактор исчезал совсем, стоило
/// администратору переключить умолчание.
///
/// ⚠ ⚠ <b>Явно выбранная почта у того, кто аутентификатор завёл, остаётся почтой.</b> Первая
/// редакция ЭТОГО кода возвращала <c>totp</c> сразу, как увидит заведённый аутентификатор, — и
/// тем отменяла выбор человека молча. Поймано девятистрочной таблицей способов
/// (<c>ТаблицаСпособов.cs</c>), написанной по условию завершения этапа 17.7: строка «<c>email</c>
/// · аутентификатор есть · почта есть» разошлась с кодом. Цена ошибки — потерявший телефон не
/// может переключиться на письмо, то есть заперт снаружи собственной учётной записи.
///
/// ⚠ <b>Два послабления, оба намеренные и оба вниз:</b>
///
/// <list type="number">
/// <item><b><c>totp</c> у того, кто аутентификатор не завёл, подменяется почтой.</b> Иначе
/// переключение настройки заперло бы снаружи всех, кто до неё не успел.</item>
/// <item><b><c>email</c> при ненастроенной почте означает отсутствие фактора.</b> Требовать
/// код, который некуда послать, — это запертая дверь без ключа.</item>
/// </list>
///
/// ⚠ <b>Второе послабление — ПРИНЯТЫЙ РИСК, а не свойство.</b> Установка, где почта не
/// настроена и аутентификатор не заведён, пускает по одному паролю. Риск виден на экране
/// настроек и записан строкой в <c>docs/security/RISKS.md</c> (правило 28); прятать его в коде
/// нельзя.
/// </remarks>
internal sealed class SecondFactorPolicy(
    TwoFactorService factors, IMailQueue mail, ISettingsReader settings)
{
    /// <summary>Каким будет фактор при следующем входе этого человека.</summary>
    public async Task<string> ResolveAsync(User user, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(user);

        var завёл = await factors.ConfirmedAsync(user.Id, cancellationToken);

        // ⚠ Аутентификатор перевешивает УМОЛЧАНИЕ СИСТЕМЫ, но не собственный выбор человека:
        // «выбора нет» у того, кто аутентификатор завёл, читается как «аутентификатор», а не
        // как то, что стоит в настройке установки.
        var выбран = user.SecondFactorMethod
            ?? (завёл
                ? SecondFactorMethods.Totp
                : await settings.GetAsync(IdentitySettings.SecondFactor, cancellationToken));

        // Выбранный аутентификатор, который заведён, — и решать больше нечего.
        // мутация 2026-08-29: вернул прежний порядок (`if (завёл) return Totp;` сразу) →
        // покраснела ТаблицаСпособов.Строка_таблицы(email, есть, есть) — выбор человека отменялся.
        if (выбран == SecondFactorMethods.Totp && завёл)
        {
            return SecondFactorMethods.Totp;
        }

        // ⚠ ⚠ Почта настроена — спрашиваем письмом, ДАЖЕ у того, кто завёл аутентификатор.
        // Это выглядит понижением защиты и им не является: человек выбрал письмо сам, а отнять
        // у него этот выбор значит запереть снаружи потерявшего телефон. Сюда же попадает
        // подмена незаведённого `totp` и любое незнакомое значение настройки: письмо — безопасное
        // направление отката, `none` — нет.
        if (await mail.CanSendAsync(cancellationToken))
        {
            return SecondFactorMethods.Email;
        }

        // Почты нет. Аутентификатор при этом заведён — спрашиваем его, даже если выбрана была
        // почта: отказаться от фактора нельзя, а настроенный способ у человека остался.
        return завёл ? SecondFactorMethods.Totp : SecondFactorMethods.None;
    }

    /// <summary>
    /// Чем этот человек может подтвердить вход прямо сейчас.
    /// </summary>
    /// <remarks>
    /// ⚠ ⚠ <b>Заведено ради экрана «нет доступа к коду?» (решение 0061).</b> Кодов
    /// восстановления в системе нет, и запасной путь у потерявшего телефон один — письмо. Чтобы
    /// экран мог его предложить, он обязан знать, что письмо тут вообще возможно: на установке
    /// без почты предложение переключиться было бы кнопкой в никуда.
    ///
    /// ⚠ <b>Это НЕ выбор человека и не умолчание установки, а наличие.</b> Аутентификатор в
    /// списке, если он заведён и подтверждён; почта — если её есть чем отправить. Список пуст
    /// ровно тогда, когда фактора нет вовсе.
    ///
    /// ⚠ <b>Спрашивается ПОСЛЕ пароля.</b> До него он был бы оракулом: «у этого адреса включён
    /// аутентификатор» — сведение о чужой учётной записи, выданное тому, кто адрес просто угадал.
    /// </remarks>
    public async Task<IReadOnlyList<string>> AvailableAsync(
        User user, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(user);

        var способы = new List<string>(2);

        if (await factors.ConfirmedAsync(user.Id, cancellationToken))
        {
            способы.Add(SecondFactorMethods.Totp);
        }

        if (await mail.CanSendAsync(cancellationToken))
        {
            способы.Add(SecondFactorMethods.Email);
        }

        return способы;
    }

    /// <summary>Годится ли значение как СОБСТВЕННЫЙ выбор. <c>null</c> — «как в системе».</summary>
    /// <remarks>
    /// ⚠ ⚠ <b>Проверяется по <c>Choosable</c>, а не по <c>All</c>:</b> <c>none</c> не
    /// выбирается вовсе. Прежняя редакция принимала его и отвергала следующей проверкой, если
    /// фактор обязателен, — то есть ровно тем способом, который условие завершения этапа 17.7
    /// называет неверным: «список это показывает, а не отвергает выбор после нажатия».
    /// </remarks>
    public static bool Выбираем(string? method) =>
        method is null || SecondFactorMethods.Choosable.Contains(method, StringComparer.Ordinal);
}
