using EmailSslSender.Modules.Identity.Domain;
using EmailSslSender.Shared.Contracts.Mail;

namespace EmailSslSender.Modules.Identity.TwoFactor;

/// <summary>
/// Каким быть второму фактору у этого человека.
/// </summary>
/// <remarks>
/// ⚠ ⚠ ⚠ <b>Подтверждённый аутентификатор решает ВСЁ, и письмо его не заменяет никогда</b>
/// (ревью безопасности 2026-10-20). Прежде письмо было запасным путём у того, кто аутентификатор
/// завёл: его предлагал экран «нет доступа к коду?», и его же давал собственный выбор
/// человека. Вместе с публичным «забыл пароль», которому тоже нужен только ящик, это складывалось
/// в цепочку «ящик → новый пароль → вход → код письмом → тот же ящик», и чужой с доступом к
/// почте забирал учётную запись под аутентификатором, ни разу не коснувшись телефона. Каждая
/// учётная запись здесь — администратор, раздающий закрытые ключи. Теперь у того, кто
/// аутентификатор подтвердил, второй фактор — только он: письмо не выбирается, не предлагается
/// и не принимается (<c>SignInService</c>). Потерявшему телефон фактор снимает другой
/// администратор («сбросить 2FA») или консольная <c>reset-superadmin-2fa</c>.
///
/// ⚠ ⚠ <b>Способ не опускается ниже того, что у человека фактически есть.</b> Завёл
/// аутентификатор — фактор <c>totp</c>, что бы ни стояло в настройке установки и в собственном
/// выборе. Это <b>регрессия эталона</b>, а не улучшение по вкусу: там первая редакция читала
/// только «выбор человека или умолчание системы», и у человека с заведённым аутентификатором
/// фактор исчезал совсем, стоило администратору переключить умолчание.
///
/// ⚠ <b>Два послабления, оба намеренные и оба вниз:</b>
///
/// <list type="number">
/// <item><b><c>totp</c> у того, кто аутентификатор не завёл, подменяется почтой.</b> Иначе
/// переключение настройки заперло бы снаружи всех, кто до неё не успел.</item>
/// <item><b><c>email</c> при ненастроенной почте означает отсутствие фактора.</b> Требовать
/// код, который некуда послать, — это запертая дверь без ключа.</item>
/// </list>
///
/// ⚠ <b>Второе послабление — ПРИНЯТЫЙ РИСК, а не свойство.</b> Установка, где почта не
/// настроена и аутентификатор не заведён, пускает по одному паролю. Риск виден на экране
/// настроек и записан строкой в <c>docs/security/RISKS.md</c> (правило 28); прятать его в коде
/// нельзя.
/// </remarks>
internal sealed class SecondFactorPolicy(TwoFactorService factors, IMailQueue mail)
{
    /// <summary>Каким будет фактор при следующем входе этого человека.</summary>
    public async Task<string> ResolveAsync(User user, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(user);

        // ⚠ ⚠ ⚠ Подтверждённый аутентификатор — и решать больше нечего: ни выбор человека, ни
        // настройка установки, ни работающая почта его не заменяют (разбор — в примечании к
        // классу). Прежняя редакция отдавала письмо тому, кто выбрал его сам при заведённом
        // аутентификаторе, — и этим открывала вход по одному ящику.
        if (await factors.ConfirmedAsync(user.Id, cancellationToken))
        {
            return SecondFactorMethods.Totp;
        }

        // ⚠ Аутентификатора нет — и выбор человека с умолчанием установки больше ничего не
        // различают: выбранный `totp` без аутентификатора подменяется письмом (первое
        // послабление), выбранное письмо — письмо. Почта настроена — спрашиваем письмом; сюда же
        // попадает любое незнакомое значение настройки: письмо — безопасное направление отката,
        // `none` — нет. Почты нет — фактора нет (второе послабление).
        //
        // ⚠ Поэтому настройка `auth.second_factor` здесь даже не читается. Прежде читалась, и
        // ответ от неё не зависел ни в одной строке таблицы способов (`ТаблицаСпособов.cs`).
        return await mail.CanSendAsync(cancellationToken)
            ? SecondFactorMethods.Email
            : SecondFactorMethods.None;
    }

    /// <summary>
    /// Чем этот человек может подтвердить вход прямо сейчас.
    /// </summary>
    /// <remarks>
    /// Заведено ради экрана второго шага входа: он показывает кнопку «код на почту» только там,
    /// где письмо действительно примут. На установке без почты такая кнопка была бы кнопкой в
    /// никуда.
    ///
    /// ⚠ ⚠ ⚠ <b>Письма в списке НЕТ у того, кто подтвердил аутентификатор</b> (ревью безопасности
    /// 2026-10-20). Прежде список был «наличием»: аутентификатор, если заведён, плюс почта, если
    /// есть чем слать, — и экран «нет доступа к коду?» предлагал письмо как запасной путь. Ровно
    /// этот путь и превращал ящик в единственный ключ от учётной записи (разбор — в примечании к
    /// классу). Теперь список — ровно то, чем вход будет принят: у владельца аутентификатора —
    /// только он, у прочих — письмо, если есть почта. Список пуст ровно тогда, когда фактора нет
    /// вовсе.
    ///
    /// ⚠ <b>Спрашивается ПОСЛЕ пароля.</b> До него он был бы оракулом: «у этого адреса включён
    /// аутентификатор» — сведение о чужой учётной записи, выданное тому, кто адрес просто угадал.
    /// </remarks>
    public async Task<IReadOnlyList<string>> AvailableAsync(
        User user, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(user);

        if (await factors.ConfirmedAsync(user.Id, cancellationToken))
        {
            return [SecondFactorMethods.Totp];
        }

        return await mail.CanSendAsync(cancellationToken) ? [SecondFactorMethods.Email] : [];
    }

    /// <summary>Годится ли значение как СОБСТВЕННЫЙ выбор. <c>null</c> — «как в системе».</summary>
    /// <remarks>
    /// ⚠ ⚠ <b>Проверяется по <c>Choosable</c>, а не по <c>All</c>:</b> <c>none</c> не
    /// выбирается вовсе. Прежняя редакция принимала его и отвергала следующей проверкой, если
    /// фактор обязателен, — то есть ровно тем способом, который условие завершения этапа 17.7
    /// называет неверным: «список это показывает, а не отвергает выбор после нажатия».
    /// </remarks>
    public static bool Выбираем(string? method) =>
        method is null || SecondFactorMethods.Choosable.Contains(method, StringComparer.Ordinal);
}
