namespace EmailSslSender.Modules.Identity.TwoFactor;

/// <summary>
/// Чем подтверждают вход.
/// </summary>
/// <remarks>
/// ⚠ <b>Строками, а не перечислением, и это осознанно:</b> значение живёт в колонке и в
/// настройке <c>auth.second_factor</c>, то есть в <c>jsonb</c> и в тексте. Перечисление
/// пришлось бы разбирать на границе, а разбор с откатом на умолчание при незнакомом значении —
/// ровно то место, где молча теряют фактор.
/// </remarks>
internal static class SecondFactorMethods
{
    /// <summary>Одноразовый код письмом.</summary>
    public const string Email = "email";

    /// <summary>Код из приложения-аутентификатора.</summary>
    public const string Totp = "totp";

    /// <summary>Фактора нет.</summary>
    public const string None = "none";

    /// <summary>Все три, в порядке убывания надёжности.</summary>
    public static readonly IReadOnlyList<string> All = [Totp, Email, None];

    /// <summary>Что человек может выбрать себе.</summary>
    /// <remarks>
    /// ⚠ ⚠ <b><c>None</c> здесь отсутствует намеренно.</b> Фактор обязателен всем, выбирается
    /// только способ (решение владельца эталона 2026-08-18), и <b>список обязан это показывать, а
    /// не отвергать выбор после нажатия</b> — иначе человек видит переключатель «выключить»,
    /// нажимает его и получает отказ. <c>None</c> остаётся возможным ИСХОДОМ разрешения — когда
    /// нет ни почты, ни аутентификатора, — но не решением человека.
    ///
    /// ⚠ <c>null</c> в этот список не входит и проверяется отдельно: он значит «как в системе»,
    /// то есть отказ от собственного выбора, а не выбор.
    /// </remarks>
    // мутация 2026-08-29: дописал сюда None → покраснела
    // ТаблицаСпособов.Отказаться_от_фактора_нельзя.
    public static readonly IReadOnlyList<string> Choosable = [Totp, Email];
}
