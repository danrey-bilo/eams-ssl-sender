namespace EmailSslSender.Api.Infrastructure;

/// <summary>
/// Номер обращения: рождается на входе, попадает в лог, в ответ и в журнал аудита.
/// </summary>
/// <remarks>
/// Один номер связывает три вещи, которые иначе не сшить: строку в логе, ответ, который
/// увидел человек, и запись в журнале аудита. Без него разбор обращения «у меня не
/// открылся пароль в 14:20» начинается с поиска по времени.
///
/// Заголовок с входа <b>принимается</b>: за туннелем и обратным прокси номер может быть
/// присвоен раньше нас, и заводить свой означало бы разорвать цепочку ровно там, где она
/// нужнее всего.
/// </remarks>
public sealed class RequestIdMiddleware(RequestDelegate next, ILogger<RequestIdMiddleware> log)
{
    /// <summary>Имя заголовка — общее на вход и на выход.</summary>
    public const string HeaderName = "X-Request-ID";

    /// <summary>Ключ в <see cref="HttpContext.Items"/>, откуда номер берут остальные.</summary>
    public const string ItemKey = "sender.request_id";

    public async Task InvokeAsync(HttpContext context)
    {
        var requestId =
            (context.Request.Headers[HeaderName].FirstOrDefault() is { Length: > 0 } incoming
                ? Trim(incoming)
                : null)
            ?? Guid.CreateVersion7().ToString("n");

        context.Items[ItemKey] = requestId;

        // Заголовок ставится ДО обработки: если обработчик начнёт писать тело, заголовки
        // уже отправлены, и добавить их будет некуда.
        context.Response.Headers[HeaderName] = requestId;

        // Область логирования: номер попадает в каждую строку внутри запроса сам, без
        // передачи параметром через все слои. `DefineScope` вместо словаря — прежний
        // `BeginScope(new Dictionary…)` заводил словарь и упаковку на КАЖДЫЙ запрос,
        // включая /api/health (этап 23.5).
        using (Область(log, requestId))
        {
            await next(context);
        }
    }

    /// <summary>Готовая область с номером обращения — ноль словарей на запрос.</summary>
    private static readonly Func<Microsoft.Extensions.Logging.ILogger, string, IDisposable?> Область =
        Microsoft.Extensions.Logging.LoggerMessage.DefineScope<string>("request_id:{RequestId}");

    /// <summary>
    /// Чужой номер обрезается и просеивается по составу.
    /// </summary>
    /// <remarks>
    /// Длина: строка произвольной длины в каждой записи лога — это способ раздуть журнал
    /// бесплатно.
    ///
    /// ⚠ ⚠ <b>Состав проверяется с этапа 59.6, и до него не проверялся вовсе.</b> Значение
    /// уезжает в заголовок ответа, а Kestrel отвергает управляющий знак в заголовке
    /// исключением — то есть номер с управляющим знаком внутри давал <b>пятисотку на любом
    /// эндпоинте</b>, включая <c>/api/health</c>. Дёшево и шумно: положить установку на лопатки
    /// одним заголовком.
    ///
    /// ⚠ Второй довод — тот же номер попадает в конверт ошибки, то есть <b>отражается клиенту</b>.
    /// Отражённое значение обязано иметь известный состав до того, как ответы начнут сжиматься
    /// (этап 60.1): именно отражение чужой строки рядом с секретом делает возможным BREACH.
    /// Здесь секрета рядом нет, и просеивание закрывает вопрос заранее.
    ///
    /// ⚠ Не подошедший номер не отвергается запросом, а <b>заменяется своим</b>: отказать в
    /// обслуживании из-за кривого заголовка значило бы поменять одну пятисотку на другую.
    /// Цепочка с прокси при этом рвётся — но она уже была порвана тем, кто прислал такое
    /// значение.
    ///
    /// ⚠ ⚠ <b>Отсеиваются УПРАВЛЯЮЩИЕ знаки, а не «всё, кроме списка разрешённых».</b> Первая
    /// редакция правки была списком (<c>A–Z a–z 0–9 . _ -</c>) — и её отверг существующий факт
    /// <c>ErrorEnvelope.Свой_номер_обращения_принимается_а_не_подменяется</c>, который шлёт
    /// номер <b>кириллицей</b>. Приём чужого номера как есть — записанное намерение, а не
    /// недосмотр: за туннелем номер присваивают раньше нас, и сужать его состав до ASCII значит
    /// рвать цепочку у всех, кто пишет его на своём языке. Ломается Kestrel именно от
    /// управляющих знаков; их и отсеиваем.
    /// </remarks>
    private static string? Trim(string value)
    {
        var кусок = value.Length <= 128 ? value : value[..128];

        foreach (var знак in кусок)
        {
            if (char.IsControl(знак))
            {
                return null;
            }
        }

        return кусок;
    }
}
